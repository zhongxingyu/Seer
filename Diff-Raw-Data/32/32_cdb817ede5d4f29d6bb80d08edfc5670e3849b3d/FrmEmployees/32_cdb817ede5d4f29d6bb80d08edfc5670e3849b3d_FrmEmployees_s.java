     @Override
     public boolean saveRegister() {
         try {
             int id = 0;
             id = !txtId.getText().equals("") ? Integer.valueOf(txtId.getText()) : 0;
             id = controller.saveRecord(id, txtRegister.getText(), txtCpf.getText(), 
                     txtRg.getText(), txtName.getText(), Utils.stringToDate(txtBirthDate.getText()),
                     txtCep.getText(), txtCity.getText(), cboUf.getSelectedItem().toString(),
                     txtAddress.getText(), txtAddressNumber.getText(), txtDistrict.getText(),
                     txtPhone.getText(), txtCellphone.getText(), txtWorkRegister.getText(),
                     txtEmail.getText(), txtReservist.getText(),txtVoterRegistration.getText(),
                     chkVoted.isSelected(), txtObservation.getText(), strImage, 
                     chkActive.isSelected(), FrmMain.currentBranch.getId());
            String newImgName = "emp" + id;
             if(Utils.renameFile(FrmMain.PATH_EMPLOYEE_IMAGES + strImage, FrmMain.PATH_EMPLOYEE_IMAGES + newImgName)) {
                 controller.updateOnlyImageName(id, newImgName);
             }
             
             txtId.setText(String.valueOf(id));
             Utils.showInfoMessage(this, SAVE_SUCCESS);
             resetList();
             return true;
         } catch (BeanValidationException e) {
             Utils.showErrorMessage(this, e.getMessage());
         } catch (Exception e) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, e);
             Utils.showErrorMessage(this, SAVE_ERROR);
         }
         return false;
     }
 
     @Override
     public boolean deleteRegister() {
         if(!Utils.showQuestionMessage(this, DELETE_CONFIRMATION)) { return false; }
         try {
             controller.inative(Integer.valueOf(txtId.getText()));
             newRegister();
             resetList();
             return true;
         } catch (Exception ex) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, ex);
             Utils.showErrorMessage(this, DELETE_ERROR);
             return false;
         }
     }
     
     @Override
     public void getValues(Employees register) {
         txtId.setText(String.valueOf(register.getId()));
         txtRegister.setText(register.getRegister());
         txtName.setText(register.getName());
         chkActive.setSelected(register.isActive());
         try {
             txtBirthDate.setText(Utils.dateToString(register.getBirthDate()));
         } catch (ParseException ex) {
             Logger.getLogger(FrmEmployees.class.getName()).log(Level.SEVERE, null, ex);
         }
         
         txtCep.setText(register.getAddress().getCep());
         txtCity.setText(register.getAddress().getCity());
         cboUf.setSelectedItem(register.getAddress().getUf());
         txtAddress.setText(register.getAddress().getAddress());
         txtAddressNumber.setText(register.getAddress().getAddressNumber());
         txtDistrict.setText(register.getAddress().getDistrict());
         
         txtPhone.setText(register.getPhone());
         txtCellphone.setText(register.getCellPhone());
         
         txtCpf.setText(register.getCpfCnpj());
         txtRg.setText(register.getRg());
         txtWorkRegister.setText(register.getWorkRegister());
         txtEmail.setText(register.getEmail());
         
         txtReservist.setText(register.getReservist());
         txtVoterRegistration.setText(register.getVoterRegistration());
         chkVoted.setSelected(register.isVoted());
         txtObservation.setText(register.getObservation());
         strImage = register.getImgPhoto();
         openImage();
         controller.setNewRecord(false);
     }
     
     private void setCepValues(String cep) {
         Address address;
         try {
             address = new AddressController().getAddressFromCep(cep);
             txtAddress.setText(address.getAddress());
             txtAddressNumber.setText(address.getAddressNumber());
             txtCity.setText(address.getCity());
             txtDistrict.setText(address.getDistrict());
             cboUf.setSelectedItem(address.getUf());
         } catch (Exception ex) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, ex);
         }
     }
     
     public final void resetList() {
         try {
             this.setList(controller.list());
             newRegister();
         } catch (Exception ex) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, ex);
         }
     }
 
     @Override
     public void searchRegister() {
         FrmEmployeesSearch search = new FrmEmployeesSearch();
         search.show();
         try {
             getValues(controller.findById(search.getReturnId()));
         } catch (Exception ex) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, ex);
         }
     }
 
