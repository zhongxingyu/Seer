 	/**
 	 * This is the main() class that is called to run the data-generating
 	 * procedure that creates instances of OrderedDiffusion and then executes
 	 * them.
 	 * 
 	 * The specific parameters used in the model are drawn from a flat random
 	 * distribution which is hard coded within this source file. This could be
 	 * externalized in a separate parameters file in the future, if necessary.
 	 * 
 	 * The number of observations is hard-coded here, with local parameter 'n'.
 	 * 
 	 * @param args
 	 *            It takes two arguments. The first is the output file name,
 	 *            which defaults to "nardiff.ordered.tsv". The second is the
 	 *            number of threads used to simultaneously execute
 	 *            OrderedDiffusion models. It defaults to 4.
 	 */
 	public static void main(String[] args) {
 		// This random seed is used only to create other random seeds.
 		MersenneTwister mainRandom = new MersenneTwister(1);
 
 		// The # of observations
 		int n = 200;
 		int replicates = 20;
 
 		// Open up a properties file
 		File propertiesFile = new File(args[0]);
 		Properties parameters = new Properties();
 		try {
 			FileReader propertiesReader = new FileReader(propertiesFile);
 			parameters.load(propertiesReader);
 		} catch (Exception e1) {
 			e1.printStackTrace();
 			return; // exit, probably
 		}
 
 		parameters.list(System.out);
 
 		n = Integer.parseInt(parameters.getProperty("n"));
 		replicates = Integer.parseInt(parameters.getProperty("replicates"));
 
 		// Initialize the data output file.
 		String outputFilename = "nardiff.ordered.tsv";
 		initOutputFile(outputFilename);
 
 		if (args.length > 1)
 			if (args[1] != null)
 				outputFilename = args[1];
 
 		// Initialize the thread pool for running OrderedDiffusion simulations
 		int numThreads = 1;
 		if (args.length > 2)
 			try {
 				Integer threads = Integer.parseInt(args[2]);
 				if (threads != null)
 					numThreads = threads;
 			} catch (Exception e) {
 				// do nothing, just use the default = 1;
 			}
 		ThreadPoolRunner tpr = new ThreadPoolRunner(numThreads);
 
 		/*
 		 * This is the primary loop for creation of OrderedDiffusion models and
 		 * the initialization of the necessary parameters. These are currently
 		 * initialized based on a random selection within a range that is
 		 * hard-coded here in the source code.
 		 */
 		for (int obs = 0; obs < n; obs++) {
 
 			for (int replicate = 0; replicate < replicates; replicate++) {
 
 				final OrderedDiffusion od = new OrderedDiffusion();
 				od.numAttachments = Integer.parseInt(parameters
 						.getProperty("numAttachmentsFixed"));
 				int numAttachmentsRandom = Integer.parseInt(parameters
 						.getProperty("numAttachmentsRandom"));
 				if (numAttachmentsRandom != 0)
 					od.numAttachments += mainRandom.nextInt(od.numAttachments);
 
 				od.totalPopulation = Integer.parseInt(parameters
 						.getProperty("totalPopulation"));
 				od.numTotalInfoPieces = Integer.parseInt(parameters
 						.getProperty("numTotalInfoPiecesFixed"));
 				int numTotalInfoPiecesRandom = Integer.parseInt(parameters
 						.getProperty("numTotalInfoPiecesRandom"));
 				if (numTotalInfoPiecesRandom != 0)
 					od.numTotalInfoPieces += mainRandom
 							.nextInt(numTotalInfoPiecesRandom);
 
 				od.numInitialInfoPieces = Integer.parseInt(parameters
 						.getProperty("numInitialInfoPiecesFixed"));
 				int numInitialInfoPiecesRandom = Integer.parseInt(parameters
 						.getProperty("numInitialInfoPiecesRandom"));
 				if (numInitialInfoPiecesRandom != 0)
 					od.numInitialInfoPieces += mainRandom
 							.nextInt(numInitialInfoPiecesRandom);
 
 				od.probKnowledgeXmit = Float.parseFloat(parameters
 						.getProperty("probKnowledgeXmit"));
 
 				od.opinionLeaderChance = Float.parseFloat(parameters
 						.getProperty("opinionLeaderChance"))
 						+ Float.parseFloat(parameters
 								.getProperty("opinionLeaderChanceRandom"))
 						* mainRandom.nextFloat();
 
 				od.opinionLeaderAlpha = Float.parseFloat(parameters
 						.getProperty("opinionLeaderAlpha"))
 						+ Float.parseFloat(parameters
 								.getProperty("opinionLeaderAlphaRandom"))
 						* mainRandom.nextFloat();
 
 				od.opinionFollowerAlpha = Float.parseFloat(parameters
 						.getProperty("opinionFollowerAlpha"))
 						+ Float.parseFloat(parameters
 								.getProperty("opinionFollowerAlphaRandom"))
 						* mainRandom.nextFloat();
 
 				od.opinionLeaderChanceBackward = Float.parseFloat(parameters
 						.getProperty("opinionLeaderChanceBackward"))
 						+ Float.parseFloat(parameters
 								.getProperty("opinionLeaderChanceBackwardRandom"))
 						* mainRandom.nextFloat();
 
 				od.opinionFollowerChanceBackward = Float.parseFloat(parameters
 						.getProperty("opinionFollowerChanceBackward"))
 						+ Float.parseFloat(parameters
 								.getProperty("opinionFollowerChanceBackwardRandom"))
 						* mainRandom.nextFloat();
 
 				od.reorderProb = Float.parseFloat(parameters
 						.getProperty("reorderProbFixed"))
 						+ Float.parseFloat(parameters
 								.getProperty("reorderProbRandom"))
 						* mainRandom.nextFloat();
 
 				od.flipsToCheck = Integer.parseInt(parameters
 						.getProperty("flipsToCheck"));
 				int flipsToCheckRandom = Integer.parseInt(parameters
 						.getProperty("flipsToCheck"));
 				if (flipsToCheckRandom != 0)
 					od.flipsToCheck += mainRandom.nextInt(flipsToCheckRandom);
 
 				od.stepsLimit = Integer.parseInt(parameters
 						.getProperty("stepsLimit"));
 
 				od.similarityProbMin = Float.parseFloat(parameters
 						.getProperty("similarityProbMin"));
 
 				od.similarityProbMax = Float.parseFloat(parameters
 						.getProperty("similarityProbMax"));
 				od.sigmoidCenter = Float.parseFloat(parameters
 						.getProperty("sigmoidCenter"));
 
 				od.modelID = modelsCreated++;
 				od.randomSeed = mainRandom.nextLong();
 				od.random = new MersenneTwister(od.randomSeed);
 
 				final int o = obs;
 
 				tpr.runModel(new Runnable() {
 					@Override
 					public void run() {
 						try {
 							od.run();
 						} catch (Exception ex) {
 							ex.printStackTrace();
 							System.exit(-1);
 						}
 						System.out.println("Finished Obs " + o);
 					}
 
 				});
 
 			}
 
 		}
 
 		tpr.finish();
 		System.exit(0);
 
 	}
 
