     private void JcbCursActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JcbCursActionPerformed
         Curs c = (Curs) JcbCurs.getSelectedItem();
         JcbAssignatura.setModel(new JComboBox(c.getAssignatures().getLlistaAssignatures().toArray()).getModel());
         JcbAssignatura.setEnabled(true);
     }//GEN-LAST:event_JcbCursActionPerformed
 
     private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         if (JcbAssignatura.getSelectedIndex() == -1 || JcbCurs.getSelectedIndex() == -1) {
             JOptionPane.showMessageDialog(this, "Heu de seleccionar totes les opcions", "Alerta", JOptionPane.WARNING_MESSAGE);
         } else {
             Curs c = (Curs) JcbCurs.getSelectedItem();
             c.getAssignatures().baixaAssignatura((Assignatura) JcbAssignatura.getSelectedItem());
             JcbAssignatura.setModel(new JComboBox(c.getAssignatures().getLlistaAssignatures().toArray()).getModel());
             
             JOptionPane.showMessageDialog(this, "Assignatura donada de baixa correctament", "Enhorabona", JOptionPane.INFORMATION_MESSAGE);
             
             //Reiniciar
             JcbAssignatura.setEnabled(false);
            JcbAssignatura.removeAllItems();
         }
     }//GEN-LAST:event_jButton1ActionPerformed

