     private void connectButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_connectButtonActionPerformed
         Object selected = hostnameDropDown.getSelectedItem();
         if (selected == null) {
             JOptionPane.showMessageDialog(this, "Must specify hostname.", "Error Connecting", JOptionPane.ERROR_MESSAGE);
             return;
         }
 
         final String host = selected.toString();
         final int port;
         try {
             port = Integer.parseInt(portField.getText());
         } catch (NumberFormatException nfe) {
             JOptionPane.showMessageDialog(this, "Bad Port: \"" + portField.getText() + "\"", "Error Connecting", JOptionPane.ERROR_MESSAGE);
             return;
         }
 
         Object selectedKPObject = keyPairDropDown.getSelectedItem();
         if (selectedKPObject == null) {
             JOptionPane.showMessageDialog(this, "Must select identity.", "Error Connecting", JOptionPane.ERROR_MESSAGE);
             return;
         }
 
         final Identity selectedKP = keyLoader.getLoadedKey(keyPairDropDown.getSelectedItem().toString().trim());
 
         final String username = selectedKP.getName();
         
 
         connectionProgressBar.setVisible(true);
         connectionProgressBar.setIndeterminate(true);
         connectButton.setEnabled(false);
 
         SwingWorker x = new SwingWorker() {
             private MetaFrame nextFrame;
             @Override
             protected ActionStatus doInBackground() {
                 thisFrame.protocol = new MCTClientProtocol(host, port, keyLoader, username, selectedKP.getPubKey(), selectedKP.getPrivateKey());
                 try {
                     protocol.doInitialKeyExchange();
                 } catch (UnknownHostException ex) {
                     return ActionStatus.UNKNOWN_HOST;
                 } catch (IOException ex) {
                     return ActionStatus.CONNECTION_REFUSED;
                 } catch (ClassNotFoundException | NoSuchAlgorithmException | NoSuchPaddingException | InvalidKeyException | IllegalBlockSizeException | BadPaddingException ex) {
                     return ActionStatus.UNHANDLED_ERROR;
                 } catch (AuthenticationAttemptRejectedException ex) {
                     return ActionStatus.CLIENT_FAILED_SERVER_CHALLENGE;
                 } catch (ServerTrustException ex) {
                     return ex.getReason();
                 }
 
                 nextFrame = new MetaFrame(new LocalClient(), thisFrame.protocol);
                 return ActionStatus.NO_FAILURE;
             }
 
             @Override
             protected void done() {
                 connectionProgressBar.setIndeterminate(false);
                 connectionProgressBar.setVisible(false);
                 ActionStatus failReason;
                 try {
                     failReason = (ActionStatus) get();
                 } catch (InterruptedException | ExecutionException ex) {
                     Logger.getLogger(ConnectionFrame.class.getName()).log(Level.SEVERE, null, ex);
                     failReason = null;
                 }
                 if (failReason == null) {
                     JOptionPane.showMessageDialog(thisFrame, "Unknown error. Sorry this message couldn't be more helpful.", "Error Connecting", JOptionPane.ERROR_MESSAGE);
                     return;
                 }
                 switch (failReason) {
                     case CLIENT_FAILED_SERVER_CHALLENGE:
                         JOptionPane.showMessageDialog(thisFrame, "Identity rejected; not authorized.", "Error Connecting", JOptionPane.ERROR_MESSAGE);
                         connectButton.setEnabled(true);
                         break;
                     case SERVER_FAILED_CLIENT_CHALLENGE:
                         JOptionPane.showMessageDialog(null, SERVER_FAIL_CHALLENGE_MESSAGE, "Possible Security Issue", JOptionPane.ERROR_MESSAGE);
                         connectButton.setEnabled(true);
                         break;
                     case SERVER_PUBLIC_KEY_MISMATCH:
                         JOptionPane.showMessageDialog(null, SERVER_KEY_MISMATCH_MESSAGE, "Possible Security Issue", JOptionPane.ERROR_MESSAGE);
                         connectButton.setEnabled(true);
                         break;
                     case CONNECTION_REFUSED:
                         JOptionPane.showMessageDialog(thisFrame, "Connection refused.", "Error Connecting", JOptionPane.ERROR_MESSAGE);
 
                         connectButton.setEnabled(true);
                         break;
                     case UNHANDLED_ERROR:
                         JOptionPane.showMessageDialog(thisFrame, "Unknown error.", "Error Connecting", JOptionPane.ERROR_MESSAGE);
                         connectButton.setEnabled(true);
                         break;
                     case UNKNOWN_HOST:
                         JOptionPane.showMessageDialog(thisFrame, "Unknown host.", "Error Connecting", JOptionPane.ERROR_MESSAGE);
                         connectButton.setEnabled(true);
                         break;
                     case NO_FAILURE:
                         nextFrame.setVisible(true);
                         thisFrame.setVisible(false);
                         break;
                 }
             }
         };
 
         x.execute();
     }//GEN-LAST:event_connectButtonActionPerformed
 
