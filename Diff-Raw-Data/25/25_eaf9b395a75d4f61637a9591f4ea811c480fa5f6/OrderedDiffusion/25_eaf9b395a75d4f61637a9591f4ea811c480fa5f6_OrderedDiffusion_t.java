 	public static float normalizedDistance(byte[] source, byte[] target) {
 		int ld = LevenshteinDistance.computeDistance(source, target);
 		int length = Math.max(source.length, target.length);
 		float score = OrderedPerson.normalizedProximity(ld, length);
 		return score;
 	}
 
 	/**
 	 * Utility function to randomly shuffle byte arrays. This cannot depend on a
 	 * standardized method because we need to use a consistent random source for
 	 * reproducibility.
 	 * 
 	 * @param random
 	 * @param array
 	 */
 	public static void shuffleArray(Random random, byte[] array) {
		ArrayList<Byte> tmp = new ArrayList<Byte>();
		for (byte b : array) {
			tmp.add(b);
		}
		Collections.shuffle(tmp,random);
		for (int i = 0; i < tmp.size(); i++) {
			array[i] = tmp.get(i);
 		}
 	}
 
