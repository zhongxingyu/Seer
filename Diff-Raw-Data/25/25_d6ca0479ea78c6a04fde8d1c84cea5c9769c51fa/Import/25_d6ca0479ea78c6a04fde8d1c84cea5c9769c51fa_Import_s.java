     private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         int returnVal = jFileChooser1.showOpenDialog(this);
         if (returnVal != JFileChooser.APPROVE_OPTION)
         {
             return;
         }
         selectedFiles = jFileChooser1.getSelectedFiles();
         String filesStr = "";
         for (int i = 0; i < selectedFiles.length; i++)
         {
             filesStr += "\"" + selectedFiles[i].getAbsolutePath() + "\" ";
         }
         jTextField1.setText(filesStr);
     }//GEN-LAST:event_jButton1ActionPerformed
 
     private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
         if (jTextField1.getText().isEmpty())
         {
             JOptionPane.showMessageDialog(this,"Please choose a file first.");
             jTextField1.selectAll();
             return;
         }
 
         if (!SwingUtilities.isEventDispatchThread())
         {
             throw new RuntimeException();
         }
 
         JOptionPane.showMessageDialog(this,"Starting import, please wait..\r\nA message box will be shown upon completion.");
 
         jButton2.setEnabled(false);
         jPanel1.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
         
         isCurrentImportDone = false;
 
         XmcdImporter importer = new XmcdImporter(Database.getDataAccessLayer());
 
         thread1 = new Thread(new myThread1(importer));
         thread1.start();
 
         thread2 = new Thread(new myThread2(importer));
         thread2.start();
     }//GEN-LAST:event_jButton2ActionPerformed
 
