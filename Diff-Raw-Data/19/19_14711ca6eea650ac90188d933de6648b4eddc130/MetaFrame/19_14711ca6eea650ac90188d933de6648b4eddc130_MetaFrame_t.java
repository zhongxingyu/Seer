     public MetaFrame(LocalClient l, MCTClientProtocol p) {
         initComponents();
        this.setIconImage(new ImageIcon(getClass().getResource("/32/devices/computer.png")).getImage());
         
         localClient = l;
         protocol = p;
         globalProgressBar = progressBar;
         
         searchFieldDocument = globalSearchField.getDocument();
         searchFieldDocument.addDocumentListener(new DocumentListener() {
 
             @Override
             public void insertUpdate(DocumentEvent de) {
                 handleSearch(globalSearchField.getText().trim());
             }
 
             @Override
             public void removeUpdate(DocumentEvent de) {
                 handleSearch(globalSearchField.getText().trim());
             }
 
             @Override
             public void changedUpdate(DocumentEvent de) {
                 handleSearch(globalSearchField.getText().trim());
             }
         });
         
         overview = new OverviewPanel(l, p);
         townView = new TownViewPanel(l, p);
         territoryView = new TerritoryViewPanel(l, p);
         plotView = new PlotViewPanel(l, p);
         playerView = new PlayerViewPanel(l, p);
         securityView = new SecurityPanel(l, p);
         
         
         this.contentPanel.add(overview, overviewMenuButton.getText());
         this.contentPanel.add(townView, townMenuButton.getText());
         this.contentPanel.add(territoryView, territoryMenuButton.getText());
         this.contentPanel.add(playerView, playerMenuButton.getText());
         this.contentPanel.add(plotView, plotMenuButton.getText());
         this.contentPanel.add(securityView, securityMenuButton.getText());
         
         contentPanelLayout = (CardLayout) contentPanel.getLayout();
         this.pack();
         
         this.progressBar.setVisible(false);
         
         setLocationRelativeTo(null);
         singleton = this;
     }
 
