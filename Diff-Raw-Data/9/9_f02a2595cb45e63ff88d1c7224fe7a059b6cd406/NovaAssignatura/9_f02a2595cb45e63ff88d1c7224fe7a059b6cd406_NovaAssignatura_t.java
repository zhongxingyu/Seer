     private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         boolean incomplerts = false;
         if (jComboBox1.getSelectedIndex() == -1 || JtfCodi.getText().equals("") || JtfNom.getText().equals("")) {
             incomplerts = true;
         }
         if (!optativaOmplert() && !obligatoriaOmplert()) {
             incomplerts = true;
         }
         if (incomplerts) {
             JOptionPane.showMessageDialog(this, "Introduïu tota la informació necessària", "Alerta!", JOptionPane.WARNING_MESSAGE);
         } else {
             Curs c = (Curs) jComboBox1.getSelectedItem();
             Assignatura a = null;
 
             String nom = JtfNom.getText();
             int codi = Integer.parseInt(JtfCodi.getText());
 
             if (JrbOblig.isSelected()) {
                 int credits = Integer.parseInt(JtfCredits.getText());
                 a = new Obligatoria(codi, nom, credits);
 
             } else if (JrbOpta.isSelected()) {
                 int perfil = JcbPerfil.getSelectedIndex();
                 switch (perfil) {
                     case 0:
                         a = new Optativa(codi, nom, Optativa.PERFIL.TEORIC);
                         break;
                     case 1:
                         a = new Optativa(codi, nom, Optativa.PERFIL.PRACTIC);
                         break;
                 }
 
             }
             try {
                 inserirAssignatura(c, a);
                 JOptionPane.showMessageDialog(this, "Assignatura inserida correctamente", "Enhorabona", JOptionPane.INFORMATION_MESSAGE);
             } catch (AssignaturaExistentException ex) {
                JOptionPane.showMessageDialog(this, "L'assignatura ja existeix", "Error", JOptionPane.ERROR_MESSAGE);
             }
             netejarCamps();
 
         }
 
     }//GEN-LAST:event_jButton1ActionPerformed
