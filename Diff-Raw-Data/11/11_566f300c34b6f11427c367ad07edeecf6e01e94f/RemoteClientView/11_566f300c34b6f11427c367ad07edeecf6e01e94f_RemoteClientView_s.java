     private void jButtonExecuteCommandsActionPerformed(java.awt.event.ActionEvent evt)//GEN-FIRST:event_jButtonExecuteCommandsActionPerformed
     {//GEN-HEADEREND:event_jButtonExecuteCommandsActionPerformed
        String sep = System.getProperty("line.separator");
         String text = jTextAreaCommands.getText();
         ArrayList<String> commands = new ArrayList<>();
         if (!text.isEmpty())
         {
             String[] split = text.split(sep);
             for (String command : split)
             {
                 String finalCommand = command;
                 if (command.startsWith("/"))
                 {
                     finalCommand = command.replace("/", "");
                 }
                 commands.add(finalCommand);
             }
             controller.executeCommands(commands);
             controller.updateConsole(true);
             jTextAreaCommands.setText("");
         }
     }//GEN-LAST:event_jButtonExecuteCommandsActionPerformed
 
