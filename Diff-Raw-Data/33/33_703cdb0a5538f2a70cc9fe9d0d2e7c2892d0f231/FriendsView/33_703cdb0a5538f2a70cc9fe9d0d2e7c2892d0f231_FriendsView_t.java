     GridBagConstraints gbc = new GridBagConstraints();
    int x = 0;
    int y = 1;
     
     private void ShowList()
     {
         
         for(int i = 0; i < FacebinProfile.FRIENDMANAGER.getFriendsList().length; i++)
         {
             if(FacebinProfile.FRIENDMANAGER.friendsList[i].isAceptado()==true)
             {
                 if(FacebinProfile.FRIENDMANAGER.friendsList[i].getEmail().equals(FacebinProfile.GLOBAL_USER.getEmail()))
                 {
                     JButton friendButton = new JButton(FacebinProfile.FRIENDMANAGER.friendsList[i].getQuienInvito());
                     friendButton.setActionCommand("FriendButton");
                     friendButton.addActionListener(this);
                     friendButton.setName(FacebinProfile.FRIENDMANAGER.friendsList[i].getQuienInvito());
                     gbc.gridx = x;
                     gbc.gridy = y;
                     this.add(friendButton, gbc);
                     y += 1;
                 }
                 else
                 {
                    JButton friendButton = new JButton(FacebinProfile.FRIENDMANAGER.friendsList[i].getEmail());
                     friendButton.setActionCommand("FriendButton");
                     friendButton.addActionListener(this);
                     friendButton.setName(FacebinProfile.FRIENDMANAGER.friendsList[i].getEmail());
                     gbc.gridx = x;
                     gbc.gridy = y;
                     this.add(friendButton, gbc);
                     y += 1;
                 }
             }
         }
     }
 
     public void actionPerformed(ActionEvent e) {
         
        
        
         String command = e.getActionCommand();
         
         if(command.equals("FriendButton"))
         {
            String email = ((JButton)e.getSource()).getName();
            JOptionPane.showMessageDialog(null, email);
         }
     }
     
