     private void openAndCopyFile() {
         JFileChooser fileChooser = new JFileChooser();
         int ok = fileChooser.showOpenDialog(this);
         if(ok != JFileChooser.APPROVE_OPTION) { return; }
         File file = fileChooser.getSelectedFile();
         strImage = file.getName();
         String path = FrmMain.PATH_EMPLOYEE_IMAGES + strImage;
         try {
             Utils.copyFile(file, path);
             openImage();
         } catch (IOException ex) {
             Logger.getLogger(FrmEmployees.class.getName()).log(Level.SEVERE, null, ex);
         }
     }
 
