 package com.github.escortkeel.circle.event;
 
 import com.github.escortkeel.circle.IRCClient;
 
 /**
  * This class represents an IRC private message event, generated by an
  * <code>IRCClient</code> instance when a private message is received.
  *
  * @author Keeley Hoek (escortkeel@live.com)
  */
 public class IRCPrivateMessageEvent extends IRCMessageEvent {
 
     private final String target;
     private final String message;
 
     /**
      * Constructs a new
      * <code>IRCPrivateMessageEvent</code> with the specified parameters.
      */
     public IRCPrivateMessageEvent(IRCClient client, String source, String message) {
         super(client, source, message);
 
         int split = message.indexOf(" ");
         this.target = message.substring(0, split);
        this.message = message.substring(split + 2);
     }
 
     /**
      * Returns the target(s) of the message.
      *
      * @return the target(s).
      */
     public String getTarget() {
         return target;
     }
 
     /**
      * Returns the contents of message.
      *
      * @return the message.
      */
     public String getMessage() {
         return message;
     }
 }
