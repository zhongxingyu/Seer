     private void ShowNextQuestion()
     {
         if (questionsIterator.hasNext())
         {
             if (!SwingUtilities.isEventDispatchThread())
             {
                 throw new RuntimeException();
             }
 
             jButton1.setEnabled(false);
             jPanel1.setCursor(Cursor.getPredefinedCursor(Cursor.WAIT_CURSOR));
             thread = new Thread(new myThread());
             thread.start();
         }
         else
         {
             this.setEnabled(false);
             this.dispose();
             Gameover gameOverForm =
                     new Gameover(null, true, player, correctAnswers);
             gameOverForm.show();
         }
     }
 
     private void SwitchPanelByQuestion(Question question) {
         String type = question.getClass().toString();
         CardLayout cl = (CardLayout)(jPanelQuestion.getLayout());
         cl.first(jPanelQuestion);
         if ((type.contains("MatchQuestion")) || (type.contains("OrderedQuestion"))) {
             generateMatchOrderedQuestion(question);
             cl.next(jPanelQuestion);
             cl.next(jPanelQuestion);
         }
         else if (type.contains("MultipleChoiceQuestion")) {
             generateAmericanQuestion(question);
             cl.next(jPanelQuestion);
         }
     }
     
     private void generateAmericanQuestion(Question question) {
         MultipleChoiceQuestion concreteQuestion = (MultipleChoiceQuestion) question;
         this.jLabel4.setText(GuiUtils.getHtmlWrappedString(concreteQuestion.getQuestionText()));
         List<MultipleChoiceAnswer> answers = concreteQuestion.getAllPossibleAnswers();
         this.jRadioButton1.setText(GuiUtils.getHtmlWrappedString(answers.get(0).getAnswer()));
         this.jRadioButton2.setText(GuiUtils.getHtmlWrappedString(answers.get(1).getAnswer()));
         this.jRadioButton3.setText(GuiUtils.getHtmlWrappedString(answers.get(2).getAnswer()));
         this.jRadioButton4.setText(GuiUtils.getHtmlWrappedString(answers.get(3).getAnswer()));
         this.jRadioButton1.setSelected(true);
     }
 
     private void generateMatchOrderedQuestion(Question question) {
         this.jLabel8.setText(GuiUtils.getHtmlWrappedString(question.getQuestionText()));
 
         if (question.getClass().toString().contains("MatchQuestion")) {
             MatchQuestion concreteQuestion = (MatchQuestion) question;
             List<String> leftItems = concreteQuestion.getLeftItems();
 
             this.jLabel3.setText(GuiUtils.getHtmlWrappedString(leftItems.get(0)));
             this.jLabel5.setText(GuiUtils.getHtmlWrappedString(leftItems.get(1)));
             this.jLabel6.setText(GuiUtils.getHtmlWrappedString(leftItems.get(2)));
             this.jLabel7.setText(GuiUtils.getHtmlWrappedString(leftItems.get(3)));
 
             List<String> rightItems = concreteQuestion.getRightItems();
             jComboBox1.removeAllItems();
             jComboBox2.removeAllItems();
             jComboBox3.removeAllItems();
             jComboBox4.removeAllItems();
             for (String str : rightItems)
             {
                 jComboBox1.addItem(str);
                 jComboBox2.addItem(str);
                 jComboBox3.addItem(str);
                 jComboBox4.addItem(str);
             }
         }
         else if (question.getClass().toString().contains("OrderedQuestion")) {
             OrderedQuestion concreteQuestion = (OrderedQuestion) question;
             List<String> leftItems = concreteQuestion.getLeftItems();
             
             this.jLabel3.setText(GuiUtils.getHtmlWrappedString(leftItems.get(0)));
             this.jLabel5.setText(GuiUtils.getHtmlWrappedString(leftItems.get(1)));
             this.jLabel6.setText(GuiUtils.getHtmlWrappedString(leftItems.get(2)));
             this.jLabel7.setText(GuiUtils.getHtmlWrappedString(leftItems.get(3)));
 
             List<String> rightItems = concreteQuestion.getRightItems();
             jComboBox1.removeAllItems();
             jComboBox2.removeAllItems();
             jComboBox3.removeAllItems();
             jComboBox4.removeAllItems();
             for (String str : rightItems)
             {
                 jComboBox1.addItem(str);
                 jComboBox2.addItem(str);
                 jComboBox3.addItem(str);
                 jComboBox4.addItem(str);
             }
         }
 
     }
     
