     public EssayMarkingFrame() throws Exception {
         mkft = new MarkingFactory();
         mdlf = new ModelFactory();
         xmlf = new XMLFactory();
         mdlf.setAssessmentList((List<Assessment>)xmlf.readXMLfromFile("AssessmentXML.xml"));
         
         mkft.setHead((Answer) xmlf.readXMLfromFile("AnswerXML.xml"));
         List<int[]> positionsList = mkft.getPositionList();
         
         initComponents();
         panel = new JPanel();
         panel.setLayout(new TableLayout("cols=1 itop=0 ibottom=0 ileft=0 iright=0"));
         int i=1;
         for(int[] positions : positionsList) { //For each positions in positionsList 
             //for(int i=0; i<positionsList.size(); i++) {
               //  int[] n = positionsList.get(i);
             //}
             if (mdlf.getQuestionType(positions)=="ESQ"){
                 esp = new EssayMarkingPanel();
                 esp.setPosition(positions);
                 esp.setEdit(false);
                 String s = String.valueOf(i++ + ". ");
                 esp.setInstruction(String.format("<html><div style=\"width:%dpx;\">%s</div><html>", 630, s + mdlf.getQuestionText(positions)));
                 esp.setAnswer( mkft.getAnswerGivenFromPositions(positions));
                 esp.setAnswerSchema(mdlf.getEssayAnswerSchema(positions));
                 esp.setMark(mkft.getMarkGivenFromPositions(positions));
                 panel.add(esp);
             }
         }
         pnlContent.getViewport().add(panel);
     }
     
     
 
