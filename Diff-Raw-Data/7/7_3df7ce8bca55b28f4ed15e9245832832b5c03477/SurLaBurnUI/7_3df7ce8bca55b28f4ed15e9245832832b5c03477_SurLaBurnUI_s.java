     private void menuImportFileActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuImportFileActionPerformed
     int returnVal = fileChooser.showOpenDialog(this);
     if (returnVal == JFileChooser.APPROVE_OPTION) {
         File file = fileChooser.getSelectedFile();
         try {                  
             box.openFile(file);
             //add titles to the dropdown box
             for(int i = 0; i < box.list.size(); i++)
             {
                titlesComboBox.addItem(box.list.get(i).getTitle()); 
             }
         } catch (IOException ex) {
             Logger.getLogger(SurLaBurnUI.class.getName()).log(Level.SEVERE, null, ex);
         }
     } else {
         System.out.println("File access cancelled by user.");
     }       
     }//GEN-LAST:event_menuImportFileActionPerformed
