 package net.gongshim.gonstant;
 
 import java.io.PrintWriter;
 import java.io.StringWriter;
 import java.util.Arrays;
 
 public class Generator {
     private String[] input;
     private ConstNameGen escaper;
     private String lineSeparator;
 
     public Generator(String[] input) {
         this.input = input;
         this.lineSeparator = createLineSeperator();
         escaper = createCharEscaper();
     }
 
     public final void setEscaper(final ConstNameGen escaper) {
         this.escaper = escaper;
     }
 
     protected String createLineSeperator() {
         return System.getProperty("line.separator");
     }
 
     public final void setLineSeparator(final String lineSeparator) {
         this.lineSeparator = lineSeparator;
     }
 
     protected ConstNameGen createCharEscaper() {
         return new ConstNameGen();
     }
 
     public String generate() {
         Arrays.sort(input);
         StringBuilder buf = new StringBuilder();
         buf.append("// Generated by Gonstant(http://www.gongshim.net:8080/gonstant/)");
         buf.append(lineSeparator);
         buf.append("// do NOT modify this file.");
         buf.append(lineSeparator);
         generateConsts(buf);
         generateCodes(buf);
         return buf.toString();
     }
 
     private void generateConsts(StringBuilder buf) {
         String prevValue = null;    // for duplication check
         for (int i = 0; i < input.length; i++) {
             String value = input[i];
             if (value.equals(prevValue)) throw new IllegalStateException("Duplicated value : " + value);
             String idName = escaper.fromValue(value, true);
             String idLine = String.format("public static final int %s=%d;", idName, i);
             buf.append(idLine);
             buf.append(lineSeparator);
             prevValue = value;
         }
     }
 
     private void generateCodes(StringBuilder buf) {
         StringWriter sw = new StringWriter();
         PrintWriter w = new PrintWriter(sw);
         w.println("\tprivate static final String[] items = {");
         for (int i = 0; i < input.length; i++) {
             String val = input[i];
             w.print("\t\t\""+val+"\"");
             if (i < input.length - 1) {
                 w.print(',');
             }
             w.println();
         }
         w.println("\t};");
         w.println();
 
         w.println("\tpublic static int findByValue(final String value) {");
         w.println("\t\tint lo=0, hi=items.length-1;");
         w.println("\t\twhile(lo<=hi) {");
         w.println("\t\t\tint mid = (lo+hi)>>>1;");
         w.println("\t\t\tint midValCmp = items[mid].compareTo(value);");
         w.println("\t\t\tif(midValCmp<0) {");
         w.println("\t\t\t\tlo=mid+1;");
         w.println("\t\t\t} else if(midValCmp>0) {");
         w.println("\t\t\t\thi=mid-1;");
         w.println("\t\t\t} else {");
         w.println("\t\t\t\treturn mid;");
         w.println("\t\t\t}");
         w.println("\t\t}");
         w.println("\t\treturn ~lo;");
         w.println("\t}");
         w.println();
 
         w.println("\tpublic static int findByValue(final char[] value, final int start, final int length) {");
         w.println("\t\tint lo=0, hi=items.length-1;");
         w.println("\t\twhile(lo<=hi) {");
         w.println("\t\t\tint mid = (lo+hi)>>>1;");
         w.println("\t\t\tint midValCmp = compareStringToCharArray(items[mid], value, start, length);");
         w.println("\t\t\tif(midValCmp<0) {");
         w.println("\t\t\t\tlo=mid+1;");
         w.println("\t\t\t} else if(midValCmp>0) {");
         w.println("\t\t\t\thi=mid-1;");
         w.println("\t\t\t} else {");
         w.println("\t\t\t\treturn mid;");
         w.println("\t\t\t}");
         w.println("\t\t}");
         w.println("\t\treturn ~lo;");
         w.println("\t}");
         w.println();
 
         w.println("\tprivate static int compareStringToCharArray(final String s1, final char[] s2, final int start, final int length) {");
        w.println("\t\tint s1Len = s1.length();");
        w.println("\t\tint s2Len = length;");
        w.println("\t\tint minLen = s1Len < s2Len ? s1Len : s2Len;");
        w.println("\t\tfor(int i=0;i<minLen;i++) {");
         w.println("\t\t\tchar c1 = s1.charAt(i);");
         w.println("\t\t\tchar c2 = s2[start+i];");
         w.println("\t\t\tint cdf = c1 - c2;  // character diff");
         w.println("\t\t\tif(cdf!=0) return cdf;");
         w.println("\t\t}");
        w.println("\t\treturn s1Len - s2Len;");
         w.println("\t}");
 
         w.println("\tpublic static String getValue(final int id) { return items[id]; }");
         w.flush();
 
         buf.append( sw.toString() );
     }
 }
