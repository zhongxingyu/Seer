     private boolean optativaOmplert() {
         if (JrbOpta.isSelected() && JcbPerfil.getSelectedIndex() != -1) {
             return true;
         }
         return false;
     }
 
     private boolean obligatoriaOmplert() {
         if (JrbOblig.isSelected() && !JtfCredits.getText().equals("")) {
             return true;
         }
         return false;
     }
 
