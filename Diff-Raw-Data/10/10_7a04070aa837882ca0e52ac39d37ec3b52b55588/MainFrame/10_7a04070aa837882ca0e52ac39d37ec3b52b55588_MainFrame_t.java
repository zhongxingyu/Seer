     private void settingsMenuItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_settingsMenuItemActionPerformed
         // TODO add your handling code here:
         Dataparser.getInstance().changeSource();
 
         if (school != null) {
             rightPanel.remove(school);
             school = new SchoolPanel();
             rightPanel.add(school);
             // school.revalidate();
             //school.repaint();
 
 
         } else if (author != null) {
             rightPanel.remove(author);
             author = new AuthorListPanel();
             rightPanel.add(author);
         } else if (stats != null) {
             rightPanel.remove(stats);
             stats = new StatisticPanel();
             rightPanel.add(stats);
         } else if (collab != null) {
             rightPanel.remove(collab);
             collab = new CollaborationPanel();
             rightPanel.add(collab);
         }
 
         rightPanel.revalidate();
         rightPanel.repaint();
     }//GEN-LAST:event_settingsMenuItemActionPerformed
 
