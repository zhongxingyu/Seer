     public boolean doUpdate() {
         if (!loadRegistrationLevels(true)) {
             return false;
         }
         
         levels.removeAllItems();
         for (RegistrationLevel level : registrationLevels) {
             levels.addItem(level);
         }
         
         return true;
     }
     
     public boolean testConnection() {
         return RESTHelper.testConnection();
     }
     
     protected boolean loadRegistrationLevels(boolean update) {
         //Check if RESTHelper is set up correctly first.
         if (!Configuration.isFullyConfigured()) {
             return false;
         }
 
         RESTHelper.setUrl(Configuration.getBaseUrl());
         RESTHelper.setEventId(Configuration.getEventId());
         RESTHelper.setApiKey(Configuration.getApiKey());
         
         //Get registration levels from database
         ArrayList<DBObject> rawLevels = new RegistrationLevel().getAll();
         
         if (update) {
             new RegistrationLevel().removeAll();
             registrationLevels = RESTHelper.getRegistrationLevels();
             
             if (registrationLevels == null) {
                 return false;
             }
         }
         else {
             if (rawLevels.size() > 0) {
                 System.out.println("Retrieved registration levels from table.");
                 for (DBObject object : rawLevels) {
                     registrationLevels.add((RegistrationLevel)object);
                 }
             }
             else {
                 registrationLevels = RESTHelper.getRegistrationLevels();
                 
                 if (registrationLevels == null) {
                     return false;
                 }
             }
         }
         
         Collections.sort(registrationLevels);
         return true;
     }
     
