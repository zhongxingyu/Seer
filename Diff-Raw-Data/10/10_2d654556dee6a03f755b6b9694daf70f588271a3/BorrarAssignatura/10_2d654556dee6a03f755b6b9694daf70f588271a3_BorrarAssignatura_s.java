     private void borrarAssignatura(int codiAssignatura) throws NoExisteixAssignatura, Llista.foraDeLimitsException {
         Assignatura assignatura = null;
         
         int i=0;
         while (i< llistaCurs.getNombreElements() && assignatura == null) {
             Curs c = llistaCurs.obtenirElement(i);
             assignatura = c.cercaAssignatura(codiAssignatura);
             
             if (assignatura != null) {
                 c.borrarAssignatura(assignatura);
                
                 int j=0;
                while (j>llistaEstudiant.getNombreElements()){
                    Llista<Referencia<Assignatura>> lra= llistaEstudiant.obtenirElement(j).getLlistaReferenciaAssignatura();
                    int k=0;
                    boolean refTrobada=false;
                    while(k<lra.getNombreElements()&&!refTrobada){
                        Referencia r=lra.obtenirElement(k);
                        Assignatura a= (Assignatura)r.getElement();
                        if(a.getCodi()==codiAssignatura){
                            lra.eliminarElement(r);
                            refTrobada=true;
                        }
                    }
                   
                 }
                 
             }
             i++;
         }
         
         if (assignatura == null) {
             throw new NoExisteixAssignatura("L'assignatura seleccionada no existeix.");
         }
         
         // borram totes les referències de l'assignatura
         int j=0;
         while (j<llistaEstudiant.getNombreElements()) {
             Estudiant e = llistaEstudiant.obtenirElement(j);
             e.borrarReferencia(codiAssignatura);
             j++;
         }
         
         
         
         
     }
     
