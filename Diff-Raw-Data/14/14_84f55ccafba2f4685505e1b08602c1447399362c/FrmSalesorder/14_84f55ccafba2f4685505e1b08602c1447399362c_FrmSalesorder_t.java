     private void initTable(SalesOrder salesOrder) {
         this.grid.setModel(getTableModel(salesOrder));
     }
 
     private void initComboBox() {
         cboStatus.removeAllItems();
         for(String status : SalesOrder.Status.values) {
             cboStatus.addItem(status);
         }
         
         cboPaymentMethod.removeAllItems();
         for(String status : SalesOrder.PaymentMethod.values) {
             cboPaymentMethod.addItem(status);
         }
     }
     
     private void fillTable(SalesOrder salesOrder) throws Exception {
         tableModel.clear();
         tableModel.removeRow(0);
         for(SalesOrderItems item : salesOrder.getItems()) {
             tableModel.addRow(item);
         }
     }
     
     private MyTableModel getTableModel(SalesOrder salesOrder) {
         try {
             /*Cria um ArrayList a partir de um array comum... precisa especificar
             qual o tipo do array, no caso é ProductsFromMenu.class */
             List<SalesOrderItems> products;
             SalesOrderItems[] itemsArray = salesOrder.getItems();
             if(itemsArray != null) {
                 products = Utils.arrayToArrayList(SalesOrderItems.class, itemsArray);
             } else {
                 products = new ArrayList<SalesOrderItems>();
                 products.add(new SalesOrderItems());
             }
             if(tableModel == null) {
                 tableModel = new SalesOrderItemsTableModel(products);
                 tableModel.setTable(grid);
             }
             return tableModel;
         } catch (Exception ex) {
             Logger.getLogger(FrmMenu.class.getName()).log(Level.SEVERE, null, ex);
             return null;
         }
     }
     
