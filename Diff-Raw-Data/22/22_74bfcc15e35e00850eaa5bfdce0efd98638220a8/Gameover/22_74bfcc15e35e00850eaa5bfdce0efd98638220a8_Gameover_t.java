     private ImageIcon getIconByResult(boolean result)
     {
        ClassLoader cl = this.getClass().getClassLoader();
         if (result)
         {
            return new ImageIcon(cl.getResource("my/triviagame/gui/resources/correct.gif"));
         }
         else
         {
            return new ImageIcon(cl.getResource("my/triviagame/gui/resources/wrong.gif"));
         }
     }
    
