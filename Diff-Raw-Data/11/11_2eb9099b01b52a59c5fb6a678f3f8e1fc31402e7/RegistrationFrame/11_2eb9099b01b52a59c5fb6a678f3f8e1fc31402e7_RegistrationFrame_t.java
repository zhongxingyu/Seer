     public RegistrationFrame() {
         initComponents();
         
         Configuration.loadConfiguration();
         boolean regLoaded = false;
         
         //Load registration levels
         if (loadRegistrationLevels(false)) {
             for (RegistrationLevel level : registrationLevels) {
                 levels.addItem(level);
             }
             
             regLoaded = true;
         }
         
         //Load saved, unsynchronized registrations
         ArrayList<DBObject> loadedRegs = new Registration().getAll();
         for(DBObject reg : loadedRegs) {
             System.out.println("REG: " + reg);
             regs.add((Registration)reg);
         }
         registrations.setListData(regs.toArray());
         
         if (!Configuration.isFullyConfigured() || !regLoaded) {
             sf.setVisible(true);
         }
     }
 
