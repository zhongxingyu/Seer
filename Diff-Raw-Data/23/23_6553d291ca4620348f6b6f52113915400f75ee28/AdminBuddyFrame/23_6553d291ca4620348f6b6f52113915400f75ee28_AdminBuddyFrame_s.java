     public static void main(String args[]) {
         try {
             javax.swing.UIManager.setLookAndFeel(javax.swing.UIManager.getSystemLookAndFeelClassName());
         } catch (ClassNotFoundException | InstantiationException | IllegalAccessException | UnsupportedLookAndFeelException ex) {
             Logger.getLogger(AdminBuddyFrame.class.getName()).log(Level.SEVERE, null, ex);
         }
         
         KeyPair keys = Keys.newRSAKeyPair(1024);
         
         Socket s;
         ObjectOutputStream oos;
         ObjectInputStream ois;
         OutputStream os;
         InputStream is;
         try {
             s = new Socket("localhost", 5000);
             os = s.getOutputStream();
             is = s.getInputStream();
             
             os.write(StatusCode.KEY_EXCHANGE_REQUESTED);
             
             oos = new ObjectOutputStream(os);
             ois = new ObjectInputStream(is);
             
             oos.writeObject(keys.getPublic());
             PublicKey serverKey = (PublicKey) ois.readObject();
             
             Integer sessionId = ois.readInt();
             EncryptedSecretKey wrapper = (EncryptedSecretKey) ois.readObject();
             
             SecretKey sessionKey = wrapper.decrypt(keys.getPrivate(), serverKey);
             s.close();
             
             //reconnect securely
             s = new Socket("localhost", 5000);
             os = s.getOutputStream();
             is = s.getInputStream();
             
             //write our intent and session id
             os.write(StatusCode.CONNECTION_REQUESTED);
             os.write(ByteBuffer.allocate(4).putInt(sessionId).array());
             
             oos = Keys.getEncryptedObjectOutputStream(sessionKey, os);
             ois = Keys.getEncryptedObjectInputStream(sessionKey, is);
        } catch (IOException | ClassNotFoundException ex) {
            Logger.getLogger(AdminBuddyFrame.class.getName()).log(Level.SEVERE, null, ex);
            return;
        } catch (NoSuchAlgorithmException | NoSuchPaddingException | InvalidKeyException | IllegalBlockSizeException | BadPaddingException | InvalidAlgorithmParameterException ex) {
             Logger.getLogger(AdminBuddyFrame.class.getName()).log(Level.SEVERE, null, ex);
             return;
         }
         
         
         ChanneledConnectionManager connection = new ChanneledConnectionManager(oos, ois);
         connection.startListenThread();
         
         AdminBuddyFrame f = new AdminBuddyFrame(connection);
         f.setVisible(true);
     }
