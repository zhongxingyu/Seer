     private void searchDialogButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchDialogButtonActionPerformed
         
         
         ArrayList<Recipe> tempList = new ArrayList();
         tempList.clear();
         if(searchComboBox.getItemCount()>1)
         searchComboBox.removeAllItems();
         
         for(int i = 0; i < box.list.size();i++)
         {
             tempList.add(box.list.get(i));
         }
        
        //WORKS
         if(recipeTitleSearch.isSelected())
         {
             
             for(int i = 0; i < tempList.size(); i++)
             {
                 if(tempList.get(i).getTitle().toLowerCase().contains(searchTextField.getText().toLowerCase()))
                 {
                     searchComboBox.addItem(tempList.get(i).getTitle());
                 }
         }
         }
         //WORKS
         if(recipeIngredientSearch.isSelected())
         {
             
             for(int i = 0; i < tempList.size(); i++)
             {
                 for(int j = 0; j < tempList.get(i).getListOfIngredients().size(); j++)
                 {
 
                     if(tempList.get(i).getListOfIngredients().get(j).getName().toLowerCase().contains(searchTextField.getText().toLowerCase()))
                     {
                         searchComboBox.addItem(tempList.get(i).getTitle());
                         break;
                     }
                 }
         }
         }
         //WORKS
         if(recipeTypeSearch.isSelected())
         {
             
             for(int i = 0; i < tempList.size(); i++)
             {
                 if(tempList.get(i).getType().toLowerCase().contains(searchTextField.getText().toLowerCase()))
                 {
                     searchComboBox.addItem(tempList.get(i).getTitle());
                 }
         }
         }
         //WORKS
         if(recipeDescriptionSearch.isSelected())
         {
             
             for(int i = 0; i < tempList.size(); i++)
             {
                 if(tempList.get(i).getDescription().toLowerCase().contains(searchTextField.getText().toLowerCase()))
                 {
                     searchComboBox.addItem(tempList.get(i).getTitle());
                 }
         }
         }
             tempList.clear();
     }//GEN-LAST:event_searchDialogButtonActionPerformed
