 package com.digt.jpa;
 
 import static javax.persistence.GenerationType.IDENTITY;
 
 import java.util.Date;
 import java.util.HashMap;
 import java.util.List;
 import java.util.Map;
 
 import javax.persistence.Basic;
 import javax.persistence.Column;
 import javax.persistence.Entity;
 import javax.persistence.FetchType;
 import javax.persistence.GeneratedValue;
 import javax.persistence.Id;
 import javax.persistence.JoinColumn;
 import javax.persistence.JoinTable;
 import javax.persistence.Lob;
 import javax.persistence.NamedQuery;
 import javax.persistence.OneToMany;
 import javax.persistence.PrePersist;
 import javax.persistence.Table;
 import javax.persistence.Temporal;
 import javax.persistence.TemporalType;
 import javax.persistence.Version;
 import javax.validation.constraints.NotNull;
 
 import org.apache.shindig.protocol.model.FilterOperation;
 import org.apache.shindig.social.opensocial.jpa.api.DbObject;
 import org.apache.shindig.social.opensocial.jpa.api.FilterCapability;
 import org.apache.shindig.social.opensocial.jpa.api.FilterSpecification;
 import org.eclipse.persistence.annotations.CascadeOnDelete;
 
 import com.digt.model.CertificateTrustedList;
 import com.digt.model.PersonCertificate;
 
 @Entity
 @Table(name = "certtrustlist") 
 @NamedQuery(name = CertificateTrustedListDb.DEL, query = "delete from CertificateTrustedListDb c where c.userId = ?1 and c.objectId in ?2")
 public class CertificateTrustedListDb implements DbObject, CertificateTrustedList {
 
 	public static final String FIND = "select c from CertificateTrustedListDb c where c.userId in ?1";
 	public static final String DEL = "q.certlist.del";
 
 	/**
 	 * The internal object ID used for references to this object. Should be generated by the
 	 * underlying storage mechanism
 	 */
 	@Id
 	@GeneratedValue(strategy = IDENTITY)
 	@Column(name = "oid")
 	private long objectId;
 
 	/**
 	 * An optimistic locking field
 	 */
 	@Version
 	@Column
 	protected long version;
 
 	@Basic(fetch=FetchType.LAZY)
 	@Column
 	@NotNull
 	@Lob
 	private byte[] data;
 
 	@Basic
 	@Column
 	@NotNull
 	private String id;
 
 	@Basic
 	@Column(length = 255)
 	@NotNull
 	protected String userId;
 
 	@Basic
 	@Temporal(TemporalType.TIMESTAMP)
 	@Column
 	private Date validFrom;
 	
 	@Basic
 	@Temporal(TemporalType.TIMESTAMP)
 	@Column
 	private Date validTo;
 	
 	@Basic
 	@Column
 	private String signerDn;
 	
 	@Basic
 	@Temporal(TemporalType.TIMESTAMP)
 	@Column
 	private Date created;
 
 	@CascadeOnDelete
 	@OneToMany(targetEntity=PersonCertificateDb.class, fetch=FetchType.LAZY)
 	@JoinTable(name="ctl_certs", joinColumns = {@JoinColumn(name="ctl_id", referencedColumnName="oid")},
 								 inverseJoinColumns = {@JoinColumn(name="cert_id", referencedColumnName="oid")})
 	private List<PersonCertificate> certificates;
 
 	private static final FilterOperation[] ALL_FILTEROPTIONS = new FilterOperation[] {
 		FilterOperation.equals, FilterOperation.contains, FilterOperation.present,
 		FilterOperation.startsWith };
 
 	private static final Map<String, FilterSpecification> FILTER_COLUMNS =
 			new HashMap<String, FilterSpecification>();
 
 	static {
 		FILTER_COLUMNS.put("objectId", new FilterSpecification("c.objectId", ALL_FILTEROPTIONS));
 		FILTER_COLUMNS.put("signerDn", new FilterSpecification("c.signerDn", ALL_FILTEROPTIONS));
 		FILTER_COLUMNS.put("dn", new FilterSpecification("c.dn", ALL_FILTEROPTIONS));
 	}
 
 	public static final FilterCapability FILTER_CAPABILITY = new FilterCapability() {
 		/**
 		 * {@inheritDoc}
 		 */
 		public String findFilterableProperty(String fieldName, FilterOperation filterOperation) {
 			FilterSpecification spec = FILTER_COLUMNS.get(fieldName);
 			if (spec != null) {
 				return spec.translateProperty(filterOperation);
 			}
 			return null;
 		}
 	};
 
 	public long getObjectId() {
 		return objectId;
 	}
 
 	@Override
 	public byte[] getData() {
 		return data;
 	}
 
 	@Override
 	public void setData(byte[] data) {
 		this.data = data;
 	}
 
 	@Override
	public String getId() {
 		return id;
 	}
 
 
 	@Override
	public void setId(String id) {
 		this.id = id;
 	}
 
 	@Override
 	public String getUserId() {
 		return userId;
 	}
 
 	@Override
 	public void setUserId(String userId) {
 		this.userId = userId;
 	}
 
 	@Override
 	public Date getValidFrom() {
 		return validFrom;
 	}
 
 	@Override
 	public void setValidFrom(Date validFrom) {
 		this.validFrom = validFrom;
 	}
 
 	@Override
 	public Date getValidTo() {
 		return validTo;
 	}
 
 	@Override
 	public void setValidTo(Date validTo) {
 		this.validTo = validTo;
 	}
 
 	@Override
 	public String getSignerDn() {
 		return signerDn;
 	}
 
 	@Override
 	public void setSignerDn(String signerDn) {
 		this.signerDn = signerDn;
 	}
 
 	@Override
 	public List<PersonCertificate> getCertificates() {
 		return certificates;
 	}
 
 	@Override
 	public void setCertificates(List<PersonCertificate> certificate) {
 		this.certificates = certificate;
 	}
 	
 	@Override
 	public Date getCreated() {
 		return created;
 	}
 
 	@Override
 	public void setCreated(Date created) {
 		this.created = created;
 	}
 
 	@PrePersist
 	protected void prePersist()
 	{
 		setCreated(new Date());
 	}
 	
 }
