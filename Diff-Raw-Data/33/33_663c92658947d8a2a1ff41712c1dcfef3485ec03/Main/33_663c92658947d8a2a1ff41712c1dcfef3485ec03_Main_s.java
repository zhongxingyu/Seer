     private void showAboutWindow()
     {
         if ((aboutForm != null) &&
             (aboutForm.isVisible()))
         {
             aboutForm.toFront();
             return;
         }
         aboutForm = new About(this, true);
         aboutForm.setVisible(true);
     }
 
