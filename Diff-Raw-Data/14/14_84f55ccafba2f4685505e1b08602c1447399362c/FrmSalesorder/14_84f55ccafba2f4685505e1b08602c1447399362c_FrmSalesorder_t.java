     @Override
     public boolean saveRegister() {
         try {
             int id = 0;
             SalesOrderItems[] items = tableModel.getArray();
             id = !txtId.getText().equals("") ? Integer.valueOf(txtId.getText()) : 0;
             id = controller.saveRecord(id, 
                     Integer.valueOf(txtIDCustomer.getText()),
                     Integer.valueOf(txtIDEmployees.getText()),
                     Integer.valueOf(txtIDTable.getText()),
                     FrmMain.currentBranch.getId(),
                     Utils.stringToDate(txtDate.getText() + txtTime.getText()),
                     controller.getCurrentTotalValue(), cboPaymentMethod.getSelectedIndex(),
                     Integer.valueOf(txtNumberPersons.getValue() + ""),
                     items, cboStatus.getSelectedIndex());
             txtId.setText(String.valueOf(id));
             Utils.showInfoMessage(this, SAVE_SUCCESS);
             resetList();
             return true;
         } catch (BeanValidationException e) {
             Utils.showErrorMessage(this, e.getMessage());
         } catch (Exception e) {
             Logger.getLogger(FrmCashflow.class.getName()).log(Level.SEVERE, null, e);
             Utils.showErrorMessage(this, SAVE_ERROR);
         }
         return false;
     }
 
     @Override
     public boolean deleteRegister() {
         if(!Utils.showQuestionMessage(this, DELETE_CONFIRMATION)) { return false; }
         try {
             controller.delete(Integer.valueOf(txtId.getText()));
             newRegister();
             resetList();
             return true;
         } catch (Exception ex) {
             Logger.getLogger(FrmSalesorder.class.getName()).log(Level.SEVERE, null, ex);
             Utils.showErrorMessage(this, DELETE_ERROR);
             return false;
         }
     }
     
     @Override
     public void getValues(SalesOrder register) {
         txtId.setText(String.valueOf(register.getId()));
         txtIDTable.setText(register.getTable().getTableNumber() + "");
         txtIDCustomer.setText(register.getCustomer().getId() + "");
         txtCustomer.setText(register.getCustomer().getName());
         
         txtIDEmployees.setText(register.getEmployee().getId() + "");
         txtEmployees.setText(register.getEmployee().getName());
         try {
             txtDate.setText(Utils.dateToString(register.getDate()));
             txtTime.setText(Utils.hourToString(register.getDate()));
         } catch (ParseException ex) {
             Logger.getLogger(FrmSalesorder.class.getName()).log(Level.SEVERE, null, ex);
         }
         cboStatus.setSelectedIndex(register.getStatus().ordinal());
         cboPaymentMethod.setSelectedIndex(register.getPaymentMethod().ordinal());
         
         txtNumberPersons.setValue(register.getNumberOfPersons());
         txtTotalValue.setText(Utils.doubleToCurrencyString(register.getTotalValue()));
         txtValuePerPerson.setText(Utils.doubleToCurrencyString(register.getValueForPerson()));
         
         enabledFields = register.getStatus() == SalesOrder.Status.OPENED;
         enableOrDisableFields();
         
         try {
             fillTable(register);
         } catch (Exception ex) {
             Logger.getLogger(FrmSalesorder.class.getName()).log(Level.SEVERE, null, ex);
         }
         controller.setNewRecord(false);
     }
     
