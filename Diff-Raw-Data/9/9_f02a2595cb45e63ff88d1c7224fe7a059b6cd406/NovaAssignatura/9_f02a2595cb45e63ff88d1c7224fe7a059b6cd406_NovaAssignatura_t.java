     private void inserirAssignatura(Curs curs, Assignatura a) throws AssignaturaExistentException {
         Iterator it = lc.getLlistaCursos().iterator();
         boolean existent = false;
         while (it.hasNext()) {
             Curs c = (Curs) it.next();
             if (c.getAssignatures().existeixAssignatura(a.getCodi())) {
                 existent = true;
             }
         }
 
         if (existent) {
             throw new AssignaturaExistentException();
         } else {
             curs.getAssignatures().inserirAssignatura(a);
         }
 
     }
 
