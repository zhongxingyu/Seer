     private void titlesComboBoxActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_titlesComboBoxActionPerformed
         JComboBox comboBox = (JComboBox) evt.getSource();
                 Object selected = comboBox.getSelectedItem();
                 for(int i = 0; i < box.list.size(); i++)
                 {
                 if(selected.toString().equals(box.list.get(i).getTitle()))
                 {
                     recipeDescriptionText.setText(box.list.get(i).getDescription());
                     recipeIngredientsText.setText(box.list.get(i).getListOfIngredients().toString());
                     recipeSteps.setText(box.list.get(i).getListOfSteps().toString());
                     recipeType.setText(box.list.get(i).getType());
                     recipeTitle.setText(box.list.get(i).getTitle());
                     recipeServes.setText(Integer.toString(box.list.get(i).getNumOfPeopleStart()));
                  }
     }//GEN-LAST:event_titlesComboBoxActionPerformed
     }
     private void getPreviousRecipeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_getPreviousRecipeActionPerformed
 String recipe = (String) titlesComboBox.getSelectedItem();
 
                    int end = box.list.size()-1;
                 for(int i = 0; i < box.list.size(); i++)
                 {
                 if(box.list.get(i).getTitle().equals(recipe))
                 {
                     if(i!=0)
                     {
                         recipeTitle.setText(box.list.get(i-1).getTitle());
                         recipeDescriptionText.setText(box.list.get(i-1).getDescription());
                         recipeIngredientsText.setText(box.list.get(i-1).getListOfIngredients().toString());
                         recipeSteps.setText(box.list.get(i-1).getListOfSteps().toString());
                         recipeType.setText(box.list.get(i-1).getType());
                         titlesComboBox.setSelectedItem(box.list.get(i-1).getTitle());
                         recipeServes.setText(Integer.toString(box.list.get(i).getNumOfPeopleStart()));
                     }
                     else
                     {
                         recipeTitle.setText(box.list.get(end).getTitle());
                         recipeDescriptionText.setText(box.list.get(end).getDescription());
                         recipeIngredientsText.setText(box.list.get(end).getListOfIngredients().toString());
                         recipeSteps.setText(box.list.get(end).getListOfSteps().toString());
                         recipeType.setText(box.list.get(end).getType());
                         titlesComboBox.setSelectedItem(box.list.get(end).getTitle());
                         recipeServes.setText(Integer.toString(box.list.get(i).getNumOfPeopleStart()));
                     }
                 }
                 }
     }//GEN-LAST:event_getPreviousRecipeActionPerformed
