     private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         if (jTextField1.getText().equals("") || jTextField2.getText().equals("") || JcbCurs.getSelectedIndex() == -1 || JcbVariable.getSelectedIndex() == -1) {
             JOptionPane.showMessageDialog(this, "Tota la informació és necessària", "Alerta!", JOptionPane.WARNING_MESSAGE);
         } else {
             int codi = Integer.parseInt(jTextField2.getText());
             String nom = jTextField1.getText();
             int tipusCurs = JcbCurs.getSelectedIndex();
             if (tipusCurs == 0) {//Batxillerat
                 int ordre = JcbVariable.getSelectedIndex();
                 Batxillerat b = null;
                 if (ordre == 0) {
                     b = new Batxillerat(codi, nom, Batxillerat.ORDRE.PRIMER);
                 } else if (ordre == 1) {
                     b = new Batxillerat(codi, nom, Batxillerat.ORDRE.SEGON);
                 } else {
                     try {
                         throw new CampsIncompletsException();
                     } catch (CampsIncompletsException ex) {
                         Logger.getLogger(NouCurs.class.getName()).log(Level.SEVERE, null, ex);
                     }
                 }
                 try {
                     inserirCurs(b);
                     JOptionPane.showMessageDialog(this, "Heu inserit un nou curs", "Enhorabona", JOptionPane.INFORMATION_MESSAGE);
                 } catch (CursExistentException ex) {
                     JOptionPane.showMessageDialog(this, "Ja existeix un curs amb aquest codi.", "Error", JOptionPane.ERROR_MESSAGE);
                 }
 
             } else {
                 int esp = JcbVariable.getSelectedIndex();
                 FormacioProfessional fp = null;
                 switch (esp) {
                     case 0:
                         fp = new FormacioProfessional(codi, nom, FormacioProfessional.ESPECIALITAT.MECANICA);
                         break;
                     case 1:
                         fp = new FormacioProfessional(codi, nom, FormacioProfessional.ESPECIALITAT.ELECTRONICA);
                         break;
                     case 2:
                         fp = new FormacioProfessional(codi, nom, FormacioProfessional.ESPECIALITAT.INFORMATICA);
                         break;
 
                 }
                 try {
                     inserirCurs(fp);
                     JOptionPane.showMessageDialog(this, "Heu inserit un nou curs", "Enhorabona", JOptionPane.INFORMATION_MESSAGE);
                 } catch (CursExistentException ex) {
                     JOptionPane.showMessageDialog(this, "Ja existeix un curs amb aquest codi.", "Error", JOptionPane.ERROR_MESSAGE);
                 }
             }
             
             
             netejarCamps();
         }
     }//GEN-LAST:event_jButton1ActionPerformed
