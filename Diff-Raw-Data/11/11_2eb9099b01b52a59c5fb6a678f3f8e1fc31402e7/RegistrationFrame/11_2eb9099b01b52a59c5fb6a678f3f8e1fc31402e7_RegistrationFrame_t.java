     private void synchronizeMenuButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_synchronizeMenuButtonActionPerformed
         System.out.println("SYNCHRONIZE PRESSED!");
         
         ArrayList<Registration> removed = new ArrayList<Registration>();
         
         for (Registration reg : regs) {
             if (RESTHelper.sendRegistration(reg)) {
                 removed.add(reg);
             }
         }
         
         for (Registration reg : removed) {
             regs.remove(reg);
         }
 
         registrations.setListData(regs.toArray());
     }//GEN-LAST:event_synchronizeMenuButtonActionPerformed
 
