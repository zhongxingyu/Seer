     private void populateGymTable() { 
         gyms.clear();
          String[] colNames = {"Name", "Address", "Max Capacity", "Price", "Equipment"};
      
         model = new DefaultTableModel(null, colNames) {
             Class[] types = new Class [] {
                 java.lang.String.class, java.lang.String.class, java.lang.Integer.class, java.lang.String.class, java.lang.String.class
             };
             boolean[] canEdit = new boolean [] {
                 false, false, false, false, false
             };
 
             public Class getColumnClass(int columnIndex) {
                 return types [columnIndex];
             }
 
             public boolean isCellEditable(int rowIndex, int columnIndex) {
                 return canEdit [columnIndex];
             }
         };
         
         
         Iterable<Entry> gymResultSet = MongoHelper.query("{id:{$gte:0}}", Gym.class, "gyms");
         
         Integer count = 0;
         
         if (gymResultSet != null) {
             //Iterate through gyms matching query
             for (Entry entry : gymResultSet) {
                 gyms.add((Gym)entry);
             Object[] o = new Object[5];
             o[0] = gyms.get(count).getName();
             o[1] = gyms.get(count).getAddress().toString();
             o[2] = gyms.get(count).getMaxCapacity();
             o[3] = gyms.get(count).printPrice();
             o[4] = gyms.get(count).getEquipment();
             //System.out.println(o[0].toString());
             model.addRow(o);
             count++;
             }
         }
         else {
             Object[] o = new Object[5];
             o[0] = "No Gyms Available";
             model.addRow(o);
         }
         
         gymCountjLabel.setText(count.toString());        
         
         
         jTable1.setModel(model);
         jTable1.setColumnSelectionAllowed(false);
         jTable1.getColumnModel().getColumn(0).setPreferredWidth(150);
         jTable1.getColumnModel().getColumn(1).setPreferredWidth(200);
         jTable1.getColumnModel().getColumn(2).setPreferredWidth(40);
         jTable1.getColumnModel().getColumn(3).setPreferredWidth(15);
         
         DefaultTableCellRenderer dtcr = new DefaultTableCellRenderer();
         dtcr.setHorizontalTextPosition(SwingConstants.RIGHT);
         dtcr.setHorizontalAlignment(SwingConstants.RIGHT);
         jTable1.getColumnModel().getColumn(3).setCellRenderer(dtcr);
         
         jTable1.getRowSorter().toggleSortOrder(0);
         
         jTable1.repaint();
         
     }
             
             
