     private void  loadSets()
     {
         try{
             String path = "sets.csv";
             BufferedReader fichierSource = new BufferedReader(new InputStreamReader(Controller.class.getResource(path).openStream()));
             String chaine;
             int i = 0;
             DefaultListModel modelTmp = new DefaultListModel();
             while((chaine = fichierSource.readLine())!=null)
             {
                 String[] tabChaine = chaine.split(";");
                 configurations.add(tabChaine);
                 modelTmp.addElement("Configuration "+i);
                 i++;
             }
             jList1.setModel(modelTmp);
             fichierSource.close();
         } catch (FileNotFoundException e)
         {
             System.out.println("Le fichier est introuvable !");
         } catch (IOException e)
         {
             System.out.println("Le fichier est illisible !");
         }
     }
     
