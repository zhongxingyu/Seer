     private void exportIdentityButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_exportIdentityButtonActionPerformed
         Object selectedIdentity = keyPairComboBox.getSelectedItem();
         if(selectedIdentity == null)
             return;
         
         String identityName = selectedIdentity.toString();
         
         JFileChooser chooser = new JFileChooser();
         chooser.setFileSelectionMode(JFileChooser.DIRECTORIES_ONLY);
         chooser.setApproveButtonText("Export Here");
         int ret = chooser.showOpenDialog(this);
         
         if(ret != JFileChooser.APPROVE_OPTION) 
             return;
         
         File exportDir = chooser.getSelectedFile();
         File exportFile = new File(exportDir, identityName + ".pub");
         boolean result = Keys.storeKey(exportFile, keyLoader.getLoadedKey(identityName).getPubKey());
         
         if(result) {
             JOptionPane.showMessageDialog(this, "Identity exported to file: " + exportFile.getAbsolutePath() + "\n\nNOTE: It is important that you do NOT rename this file.\n\n"
                     + "NOTE: This is only the PUBLIC half of your identity. If you delete\nyour identity, you will NOT be able to recover your identity from this file.");
         } else {
             JOptionPane.showMessageDialog(this, "Error exporting file. File either exists, or we don't have write permissions for the directory.", "Error", JOptionPane.ERROR_MESSAGE);
         }
     }//GEN-LAST:event_exportIdentityButtonActionPerformed
 
