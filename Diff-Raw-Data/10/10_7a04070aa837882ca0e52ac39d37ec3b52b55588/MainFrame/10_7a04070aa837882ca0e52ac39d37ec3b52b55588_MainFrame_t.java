     private void SchoolToggleButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SchoolToggleButtonActionPerformed
 
         // TODO add your handling code here:
         SchoolToggleButton.setSelected(true);
         StatisticsToggleButton.setSelected(false);
         AuthorToggleButton.setSelected(false);
           CollaborationToggleButton.setSelected(false);
 
         SchoolToggleButton.setEnabled(false);
         AuthorToggleButton.setEnabled(true);
         StatisticsToggleButton.setEnabled(true);
           CollaborationToggleButton.setEnabled(true);
 
         //set Statistics tables false, set school table true
         schoolMenuButtons(true);
         statsMenuButtons(false);
 
 
         school = new SchoolPanel();
         if (author != null) {
             rightPanel.remove(author);
             author = null;
         } else if (stats != null) {
             rightPanel.remove(stats);
             stats = null;
         } else if (collab != null) {
             rightPanel.remove(collab);
             collab = null;
         }
         rightPanel.add(school);
         rightPanel.revalidate();
     }//GEN-LAST:event_SchoolToggleButtonActionPerformed
 
