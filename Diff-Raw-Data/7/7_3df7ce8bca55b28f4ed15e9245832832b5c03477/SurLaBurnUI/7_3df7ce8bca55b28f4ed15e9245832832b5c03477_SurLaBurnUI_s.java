     private void scaleNumPeopleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_scaleNumPeopleActionPerformed
         String recipe = (String) titlesComboBox.getSelectedItem();
         double d = Double.parseDouble(scaleNumPeople.getText());
         int numPeople = (int)d;
         for(int i = 0; i < box.list.size();i++)
         {
             if(box.list.get(i).getTitle().equals(recipe))
             {
                 recipeIngredientsText.selectAll();
                 recipeIngredientsText.replaceSelection(box.list.get(i).howMany(numPeople).toString());
             }
         }
         
     }//GEN-LAST:event_scaleNumPeopleActionPerformed
