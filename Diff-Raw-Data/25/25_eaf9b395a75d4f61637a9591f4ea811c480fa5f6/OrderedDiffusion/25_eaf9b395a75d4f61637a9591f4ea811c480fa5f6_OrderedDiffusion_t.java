 	public float closerToB(Boolean leader) {
 		int numIndividuals = 0;
 		int numCloserToBackwards = 0;
 
 		for (Person p : graph.getVertices()) {
 			OrderedPerson op = (OrderedPerson) p;
 			boolean exclude = false;
 			if (leader != null)
 				if (op.leader != leader)
 					exclude = true;
 
 			if (!exclude) {
 				byte[] forward;
 				byte[] backward;
 
 				if (op.backward) {
 					backward = op.getLatentOrdering();
 					forward = new byte[backward.length];
 					Arrays.copyOf(backward, backward.length);
 					Arrays.sort(forward);
 				} else {
 					forward = op.getLatentOrdering();
 					backward = new byte[forward.length];
 					for (int i = 0; i < backward.length; i++) {
 						backward[i] = forward[forward.length - i - 1];
 					}
 				}
 
 				int ldForward = LevenshteinDistance.computeDistance(forward,
 						op.knowledge);
 				int ldBackward = LevenshteinDistance.computeDistance(backward,
 						op.knowledge);
 
 				numIndividuals++;
 				if (ldBackward < ldForward) {
 					numCloserToBackwards++;
 				}
 
 			}
 		}
 
 		return (float) numCloserToBackwards / numIndividuals;
 
 	}
 
