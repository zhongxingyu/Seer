     @Override
     public void update(Observable o, Object arg)
     {
         //FIXME: JLists verändern sich eigenartig (Welten zu groß, Namen zu klein)
         /*
          * FIXME: DRINGEND!!! Wenn man gerade noch durch eine Liste schleift,
          * gleichzeitig der Controller (mit den Daten vom Server diese aber
          * Updaten will -> Exception. Vllt mit Iterator umgehen
          */
         RemoteClientModel model = (RemoteClientModel) o;
         for (String s : model.getErrorMessages())
         {
             displayErrorMessage(s);
         }
         model.removeAllErrorMessages();
         for (String s : model.getInfoMessages())
         {
             displayInfoMessage(s);
         }
         model.removeAllInfoMessages();
         Server currentServer = model.getCurrentServer();
         if (currentServer != null)
         {
             jTextFieldServername.setText(currentServer.getName());
             jTextFieldServerAdress.setText(currentServer.getIp());
             jTextFieldPort.setText(Integer.toString(currentServer.getPort()));
             String username = currentServer.getUsername();
             if (username != null)
             {
                 jTextFieldUsername.setText(username);
                 jCheckBoxSave.setSelected(true);
             } else
             {
                 jCheckBoxSave.setSelected(false);
             }
             jPasswordFieldPassword.setText("");
         } else
         {
             jTextFieldServername.setText("");
             jTextFieldPort.setText("");
             jTextFieldUsername.setText("");
             jTextFieldServerAdress.setText("");
             jCheckBoxSave.setSelected(false);
         }
 
         if (model.isLoggedIn())
         {
             jButtonLogout.setEnabled(true);
             jButtonLogin.setEnabled(false);
             jTabbedPane.setEnabled(true);
 
             jProgressBarIOProgress.setMaximum(model.getMaxIOProgress());
             jProgressBarIOProgress.setValue(model.getCurrentIOProgress());
 
             if (model.isFtpEnabled())
             {
                 jTabbedPane.setEnabledAt(4, true);
             } else
             {
                 jTabbedPane.setEnabledAt(4, false);
             }
 
             jLabelServername.setText(model.getServerName());
             jLabelVersion.setText(model.getServerVersion());
             jLabelBukkitVersion.setText(model.getBukkitVersion());
             jLabelViewdistance.setText(Integer.toString(model.getViewdistance()));
             jCheckBoxNether.setSelected(model.isNetherAllowed());
             jCheckBoxTheEnd.setSelected(model.isTheEndAllowed());
             jCheckBoxWhitelist.setSelected(model.isWhitelistActive());
             jCheckBoxFlying.setSelected(model.isFlyingAllowed());
             jLabelMaxPlayers.setText(Integer.toString(model.getMaxPlayers()));
             jTextFieldMOTD.setText(model.getMotd());
             if (model.getDefaultGamemode() == Player.GAMEMODE_CREATIVE)
             {
                 jLabelDefaultGamemode.setText("Creative");
             } else if (model.getDefaultGamemode() == Player.GAMEMODE_SURVIVAL)
             {
                 jLabelDefaultGamemode.setText("Survival");
             }
 
             DefaultListModel<Player> dlmPlayers = (DefaultListModel<Player>) jListPlayers.getModel();
             dlmPlayers.clear();
             Player[] players = model.getPlayers();
             dlmPlayers.ensureCapacity(players.length);
             for (int i = 0; i < players.length; i++)
             {
                 dlmPlayers.addElement(players[i]);
             }
 
             DefaultListModel<World> dlmWorlds = (DefaultListModel<World>) jListWorlds.getModel();
             dlmWorlds.clear();
             World[] worlds = model.getWorlds();
             dlmWorlds.ensureCapacity(worlds.length);
             for (int i = 0; i < worlds.length; i++)
             {
                 dlmWorlds.addElement(worlds[i]);
             }
 
             DefaultListModel<String> dlm = (DefaultListModel<String>) jListAdmins.getModel();
             dlm.clear();
             String[] admins = model.getAdmins();
             dlm.ensureCapacity(admins.length);
             for (int i = 0; i < admins.length; i++)
             {
                 dlm.addElement(admins[i]);
             }
 
             dlm = (DefaultListModel<String>) jListPlugins.getModel();
             dlm.clear();
             String[] plugins = model.getPlugins();
             dlm.ensureCapacity(plugins.length);
             for (int i = 0; i < plugins.length; i++)
             {
                 dlm.addElement(plugins[i]);
             }
 
             dlm = (DefaultListModel<String>) jListWhitelistedPlayers.getModel();
             dlm.clear();
             String[] whitelistedPlayers = model.getWhitelistedPlayers();
             dlm.ensureCapacity(whitelistedPlayers.length);
             for (int i = 0; i < whitelistedPlayers.length; i++)
             {
                 dlm.addElement(whitelistedPlayers[i]);
             }
 
             dlm = (DefaultListModel<String>) jListBannedPlayers.getModel();
             dlm.clear();
             String[] bannedPlayers = model.getBannedPlayers();
             dlm.ensureCapacity(bannedPlayers.length);
             for (int i = 0; i < bannedPlayers.length; i++)
             {
                 dlm.addElement(bannedPlayers[i]);
             }
 
             try
             {
                 List<String> write = model.getWriteToConsole();
                 for (int i = 0; i < write.size(); i++)
                 {
                     jTextAreaConsoleOutput.append(write.get(i));
                     jTextAreaConsoleOutput.append(System.getProperty("line.separator"));
                 }
                 model.clearWriteToConsole();
             } catch (ConcurrentModificationException e)
             {
                 System.out.println("Es findet noch ein Schreibvorgang statt!");
             }
         } else
         {
             jTabbedPane.setSelectedIndex(0);
             jButtonLogin.setEnabled(true);
             jButtonLogout.setEnabled(false);
             jTabbedPane.setEnabled(false);
             jTextAreaConsoleOutput.setText("");
         }
 
         DefaultComboBoxModel<Server> dcbm = new DefaultComboBoxModel<>();
 
         for (Server s : model.getAllServers())
         {
             dcbm.addElement(s);
         }
         dcbm.setSelectedItem(model.getCurrentServer());
         jComboBoxKnownServers.setModel(dcbm);
 
         updateSettings(model);
     }
 
     private void updateSettings(RemoteClientModel model)
     {
         Settings settings = model.getSettings();
         boolean useConsole = settings.isUseConsole();
         boolean autoupdate = settings.isAutoupdate();
         int interval = settings.getAutoupdateInterval();
         File localFolder = settings.getLocalFolder();
         jCheckBoxSettingsConsole.setSelected(useConsole);
         jCheckBoxSettingsAutoupdate.setSelected(autoupdate);
         if (autoupdate)
         {
             jButtonSettingsChangeAutoupdateInterval.setEnabled(true);
             jTextFieldSettingsAutoUpdateTime.setEnabled(true);
             jTextFieldSettingsAutoUpdateTime.setText(Integer.toString(interval));
         } else
         {
             jButtonSettingsChangeAutoupdateInterval.setEnabled(false);
             jTextFieldSettingsAutoUpdateTime.setEnabled(false);
             jTextFieldSettingsAutoUpdateTime.setText("---");
         }
         jTextFieldSettingsLocalFolder.setText(localFolder.getPath());
     }
