     private UserDB UserManager = new UserDB();
     
     public UserModel Buscar(String search)
     {
         UserModel Friend = null;
 
         try
         {
             for(int i = 0; i > -1; i++)
             {
                 UserModel User = UserManager.leerUsuario(i);
                 String email = User.getEmail();
 
                 if(email.equals(search))
                 {
                     Friend = User;
                     break;
                 }
             }
         }
         catch (Exception e)
         {
             JOptionPane.showMessageDialog(null, "No se encontro al usuario");
         }
         
          return Friend;
     }
     
     private void ShowRequests()
     {
         
         requests = new JFrame("Solicitudes de Amistad");
         
         requestPanel = new JPanel();
         requestPanel.setLayout(new GridBagLayout());
         GridBagConstraints gbc = new GridBagConstraints();
         
         try
         {
              
              int solicitudes = 0;
              
              for(Friend a : FRIENDMANAGER.getFriendsList())
              {
                  if(a.isAceptado()==false&&a.amigo==true)
                  {
                      solicitudes += 1;
                  }
              }
              
              if(solicitudes != 0)
              {
                 JOptionPane.showMessageDialog(null, "Usted tiene " + solicitudes + " solicitud(es) de amistad");
                
                 int x = 0;
                 int y = 0;
                 for(int i = 0; i < FRIENDMANAGER.getFriendsList().length; i++)
                 {
                     if(FRIENDMANAGER.friendsList[i].amigo==true&&FRIENDMANAGER.friendsList[i].isAceptado()==false)
                     {
                         JLabel mail = new JLabel(FRIENDMANAGER.friendsList[i].getQuienInvito());
                         gbc.gridx = x;
                         gbc.gridy = y;
                         requestPanel.add(mail, gbc);
                         x += 1;
                         JCheckBox aceptar = new JCheckBox();
                         aceptar.setName(FRIENDMANAGER.friendsList[i].getQuienInvito());
                         gbc.gridx = x;
                         gbc.gridy = y;
                         requestPanel.add(aceptar, gbc);
                         x = 0;
                         y += 1;
                     }
                 }
              
                 JButton ok = new JButton("OK");
                 ok.setActionCommand("RequestsReady");
                 ok.addActionListener(this);
                 gbc.gridy = y + 1;
                 gbc.gridx = 0;
                 gbc.gridwidth = 2;
                 requestPanel.add(ok, gbc);
                 
                  requests.add(requestPanel);
                  requests.pack();
                  requests.validate();
                  requests.setVisible(true);
              }
              else 
              {
                  JOptionPane.showMessageDialog(null, "Usted no tiene solicitudes de amistad");
              }
         }
         catch(Exception e)
         {
             
         }
         
     }
     
         
     
     
     private void ApproveRequests()
     {
         for(Object a : requestPanel.getComponents())
         {
                 if(a instanceof JCheckBox)
                 {
                     if(((JCheckBox)a).isSelected()==true)
                     {
                         try
                         {
                             FRIENDMANAGER.RespondRequest(((JCheckBox)a).getName());
                         }
                         catch(Exception e)
                         {
                             
                         }
                     }
                 }
         }
         
         try
         {
             FRIENDMANAGER.getMyFriends();
         }
         catch (Exception e)
         {
             
         }
     }
     
     private void Prepare()
     {
         try
         {
             FRIENDMANAGER.getMyFriends();
             
             for(int i = 0; i < FRIENDMANAGER.friendsList.length; i++)
             {
                 
                 FRIENDMANAGER.friendsList[i].esAmigo(FacebinProfile.GLOBAL_USER.getEmail());
                 
             }
             
         }
         catch (Exception e)
         {
             
         }
     }
 
     public void actionPerformed(ActionEvent e) {
         String command = e.getActionCommand();
         
         if(command.equals("Agregar"))
         {
             String friend = ((JButton)e.getSource()).getName();
             try
             {
                 FRIENDMANAGER.sendUserRequest(friend);
                 JOptionPane.showMessageDialog(null, "Se le ha enviado la solicitude de amistad a " + friend);
             }
             catch(Exception ex)
             {
                 JOptionPane.showMessageDialog(null, "Error al enviar la solicitud de amistad a " + friend);
                System.out.println(ex.toString());
                ex.printStackTrace();
             }
         }
         else if (command.equals("RequestsReady"))
         {
             ApproveRequests();
             requests.setVisible(false);
         }
     }
 
