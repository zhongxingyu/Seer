     private class myThread1 implements Runnable
     {
         private XmcdImporter importer;
         public myThread1(XmcdImporter importer)
         {
             this.importer = importer;
         }
 
         @Override
         public void run()
         {
             try {
                 XmcdDiscArchives archives = new XmcdDiscArchives(Arrays.asList(selectedFiles), true);
                 Iterator<XmcdDisc> toImport = new XmcdFilters.Factory(archives).defaultFilters().chain();
 
                 importer.importFreedb(toImport);
                 archives.close();
                 SetResultSafely1();
             } catch (DALException ex) {
                 // TODO handle exception, report error to user
                 // If showing an error please use ex.getCause() to report the inner exception
             } catch (IOException ex) {
                 // TODO handle exception, report error to user
                 // If showing an error please use ex.getCause() to report the inner exception
             }
         }
     }
 
     private void SetResult2(long importedCount, long parsedCount)
     {
        int currImportedCount = Integer.parseInt(jLabelImportedCount.getText());
        currImportedCount += importedCount;
        jLabelImportedCount.setText(String.valueOf(currImportedCount));

        int currParsedCount = Integer.parseInt(jLabelParsedCount.getText());
        currParsedCount += parsedCount;
        jLabelParsedCount.setText(String.valueOf(currParsedCount));
     }
 
     private void SetResultSafely2(long importedCount, long parsedCount)
     {
         final long _importedCount = importedCount;
         final long _parsedCount = parsedCount;
 
         Runnable r = new Runnable()
         {
             @Override
             public void run()
             {
                 try
                 {
                     SetResult2(_importedCount, _parsedCount);
                 } catch (Exception ex)
                 {
                     Logger.getLogger(NewGame.class.getName()).log(Level.SEVERE, null, ex);
                 } 
             }
         };
 
         SwingUtilities.invokeLater(r);
     }
 
     private class myThread2 implements Runnable
     {
         private XmcdImporter importer;
         public myThread2(XmcdImporter importer)
         {
             this.importer = importer;
         }
 
         @Override
         public void run()
         {
             long importedCount;
             long parsedCount;
 
             while (!isCurrentImportDone)
             {
                 importedCount = importer.getFilesImportedCount();
                 parsedCount = importer.getFilesParsedCount();
 
                 SetResultSafely2(importedCount, parsedCount);
 
                 try {
                     Thread.sleep(500);
                 } catch (InterruptedException ex) {
                     Logger.getLogger(Import.class.getName()).log(Level.SEVERE, null, ex);
                 }
             }
         }
     }
