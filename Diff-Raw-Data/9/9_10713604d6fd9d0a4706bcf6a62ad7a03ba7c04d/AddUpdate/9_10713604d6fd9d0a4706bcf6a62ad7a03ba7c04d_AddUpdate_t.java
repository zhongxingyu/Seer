     private class Save implements Runnable
     {
         private IAlbumDescriptor albumToSave;
         private List<ITrackDescriptor> trackList;
         public Save(IAlbumDescriptor albumToSave, List<ITrackDescriptor> trackList)
         {
             this.albumToSave = albumToSave;
             this.trackList = trackList;
         }
         
         @Override
         public void run()
         {
             boolean wasOk = true;
             IDAL dataAccessLayer = Database.getDataAccessLayer();
 
             try {
                 dataAccessLayer.updateAlbum(albumToSave, trackList);
             } catch (DALException ex) {
                 Logger.getLogger(AddUpdate.class.getName()).log(Level.SEVERE, null, ex);
                 wasOk = false;
             }
             
             SetSaveResultSafely(wasOk);
         }
     }
 
     private void SetSaveResult(boolean wasOk)
     {
         jPanel1.setCursor(null);
         this.jButton1.setEnabled(true);
         if (!isNewAlbum)
         {
             this.jButton2.setEnabled(true);
         }
         this.jButton3.setEnabled(true);
         this.jButton4.setEnabled(true);
         this.jButton5.setEnabled(true);
        this.setDefaultCloseOperation(JDialog.DISPOSE_ON_CLOSE);
 
         if (!wasOk)
         {
             if (isNewAlbum)
             {
                 JOptionPane.showMessageDialog(this, "Error adding new album to db.\r\nSee log file for more details.");
             }
             else
             {
                 JOptionPane.showMessageDialog(this, "Error updating album in db.\r\nSee log file for more details.");
             }
             return;
         }
 
         JOptionPane.showMessageDialog(this, "Saved successfully.");
         if (discoverForm != null)
         {
             discoverForm.refreshSearch();
         }
         this.dispose();            
     }
 
     private void SetSaveResultSafely(boolean wasOk)
     {
         final boolean _wasOk = wasOk;
 
         Runnable r = new Runnable()
         {
             @Override
             public void run()
             {
                 SetSaveResult(_wasOk);
             }
         };
 
         SwingUtilities.invokeLater(r);
     }
 
