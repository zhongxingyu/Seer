     @Override
     public boolean saveRegister() {
         try {
             int id = 0;
             id = !txtId.getText().equals("") ? Integer.valueOf(txtId.getText()) : 0;
             id = controller.saveRecord(id, txtDescription.getText(), 
                     Utils.currencyStringToDouble(txtCurrentStock.getText().toString()),
                     Utils.currencyStringToDouble(txtMinStock.getValue().toString()), 
                     Utils.currencyStringToDouble(txtMaxStock.getValue().toString()),
                     Utils.currencyStringToDouble(txtCost.getText()), txtType.getText(),
                     Utils.stringToDate(txtValidate.getText()), txtUom.getText(),
                     Utils.currencyStringToDouble(txtMinMeasure.getText()),
                     Utils.currencyStringToDouble(txtCostMinMeasure.getText()), txtObservation.getText(),
                     chkActive.isSelected(), FrmMain.currentBranch.getId(), 
                     Utils.currencyStringToDouble(txtSalesValue.getText()), 
                     chkFinalProduct.isSelected());
             txtId.setText(String.valueOf(id));
             Utils.showInfoMessage(this, SAVE_SUCCESS);
             resetList();
             return true;
         } catch (BeanValidationException e) {
             Utils.showErrorMessage(this, e.getMessage());
         } catch (Exception e) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, e);
             Utils.showErrorMessage(this, SAVE_ERROR);
         }
         return false;
     }
 
     @Override
     public boolean deleteRegister() {
         if(!Utils.showQuestionMessage(this, DELETE_CONFIRMATION)) { return false; }
         try {
             controller.inative(Integer.valueOf(txtId.getText()));
             newRegister();
             resetList();
             return true;
         } catch (Exception ex) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, ex);
             Utils.showErrorMessage(this, DELETE_ERROR);
             return false;
         }
     }
 
     @Override
     public void getValues(Products register) {
         try {
             txtId.setText(String.valueOf(register.getId()));
             txtDescription.setText(register.getName());
             txtCurrentStock.setText(String.valueOf(register.getCurrentStock()));
             txtCostMinMeasure.setText(Utils.doubleToCurrencyString(register.getCostMinMeasure()));
             txtCost.setText(Utils.doubleToCurrencyString(register.getCost()));
             txtMinStock.setValue(register.getMinStock());
             txtMaxStock.setValue(register.getMaxStock());
             txtType.setText(register.getTypeOfProduct());
             txtUom.setText(register.getUom());
             txtMinMeasure.setText(String.valueOf(register.getMinMeasure()));
             txtValidate.setText(Utils.dateToString(register.getValidade()));
             chkActive.setSelected(register.isActive());
             txtSalesValue.setText(Utils.doubleToCurrencyString(register.getPrice()));
             chkFinalProduct.setSelected(register.isFinal());
             setProductFinal();
             txtObservation.setText(register.getObservation());
             controller.setNewRecord(false);
         } catch (ParseException ex) {
             Logger.getLogger(FrmProducts.class.getName()).log(Level.SEVERE, null, ex);
         }
     }
 
     public final void resetList() {
         try {
             this.setList(controller.list());
             newRegister();
         } catch (Exception ex) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, ex);
         }
     }
 
     @Override
     public void searchRegister() {
         FrmProductsSearch search = new FrmProductsSearch();
         search.show();
         try {
             getValues(controller.findById(search.getReturnId()));
         } catch (Exception ex) {
             Logger.getLogger(FrmCustomers.class.getName()).log(Level.SEVERE, null, ex);
         }
     }
 
     @Override
     public void setNewRegisterInController() {
         controller.setNewRecord(true);
     }
 
     private void setProductFinal() {
         lblPrice.setVisible(chkFinalProduct.isSelected());
         txtSalesValue.setVisible(chkFinalProduct.isSelected());
     }
 
