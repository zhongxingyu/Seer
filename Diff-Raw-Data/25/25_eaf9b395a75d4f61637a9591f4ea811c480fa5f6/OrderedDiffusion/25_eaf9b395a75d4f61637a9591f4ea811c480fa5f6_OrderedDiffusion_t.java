 	public float meanProximityBetween(PersonScope ps, OpinionType tt,
 			InfoScope ts) {
 		double totalProximity = 0d;
 		int numPersons = 0;
 
 		for (Person p : graph.getVertices()) {
 			OrderedPerson op = (OrderedPerson) p;
 			if (ps == PersonScope.LEADERS)
 				if (op.leader == false)
 					continue;
 			if (ps == PersonScope.FOLLOWERS)
 				if (op.leader == true)
 					continue;
 
 			List<byte[]> compareTo = new ArrayList<byte[]>();
 
 			if (tt == OpinionType.A_FORWARD) {
 				compareTo.add(Arrays.copyOf(totalTruthForward,
 						totalTruthForward.length));
 			} else if (tt == OpinionType.B_BACKWARD) {
 				compareTo.add(Arrays.copyOf(totalTruthBackward,
 						totalTruthBackward.length));
 
 			} else if (tt == OpinionType.LATENT) {
 				if (!op.backward) {
 					compareTo.add(Arrays.copyOf(totalTruthForward,
 							totalTruthForward.length));
 				} else {
 					compareTo.add(Arrays.copyOf(totalTruthBackward,
 							totalTruthBackward.length));
 				}
 			} else if (tt == OpinionType.NEIGHBORS) {
 				List<OrderedPerson> neighbors = getAdjacencies(op);
 				for (OrderedPerson nei : neighbors) {
 					compareTo.add(nei.knowledge);
 				}
 			} else {
 				throw new RuntimeException("Unknwon Opinion Type");
 			}
 
 			/*
 			 * Calculate (and perhaps average) the proximities
 			 */
 			int numIndProximities = 0;
 			double sumIndProximities = 0d;
 			for (byte[] other : compareTo) {
 				int ld = Integer.MAX_VALUE;
 				int length = 0;
 
 				if (ts == InfoScope.INTERSECTION_WITH_SEEN) {
 					Object[] intersections = OrderedPerson
 							.knowledgeIntersection(op.knowledge, other);
 					ld = LevenshteinDistance.computeDistance(
 							(byte[]) intersections[0],
 							(byte[]) intersections[1]);
 					length = Math.max(((byte[]) intersections[0]).length,
 							((byte[]) intersections[1]).length);
 				} else if (ts == InfoScope.ALL_PIECES) {
 					ld = LevenshteinDistance.computeDistance(op.knowledge,
 							other);
 					length = Math.max(op.knowledge.length, other.length);
 				} else {
 					throw new RuntimeException("Unknown Info Scope");
 				}
 				float subProx = OrderedPerson.normalizedProximity(ld, length);
 				sumIndProximities += subProx;
 				numIndProximities++;
 			}
 
 			totalProximity += (double) sumIndProximities
 					/ (float) numIndProximities;
 			numPersons++;
 		}
 
 		double meanDistance = (double) (totalProximity / numPersons);
 		return (float) meanDistance;
 	}
 
