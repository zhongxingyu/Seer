 package item;
 
 import obstacle.ForceField;
 import game.Actor;
 
 /**
  * This class represents a force field generator.
  * Force field generators are items that can be picked up and used by a player to generate a force field.
  * 
  * @author 	Groep 8
  * 
  * @version April 2013
  */
 public class ForceFieldGenerator extends PortableItem {
 	
 	/**
 	 * The force field corresponding with this force field generator.
 	 */
	private ForceField forcefield = new ForceField();
 	
 	/**
 	 * This method returns the corresponding force field.
 	 * 
 	 * @return	this.forcefield
 	 * 			| The forcefield generated by this force field generator.
 	 */
 	public ForceField getForceField() {
 		return forcefield;
 	}
 
 	/**
 	 * This method sets the force field corresponding with this force field generator.
 	 * 
 	 * @param 	forcefield
 	 * 			The force field now corresponding with the force field generator.
 	 * 
 	 * @effect	The force field is set.
 	 * 			| new.forcefield = forcefield
 	 */
 	public void setForceField(ForceField forcefield) {
 		this.forcefield = forcefield;
 	}
 
 	/**
 	 * This method specifies what happens when an Actor starts on a force field generator.
 	 * 
 	 * @param	actor
 	 * 			This is the Actor starting on the generator.
 	 */
 	@Override
 	public void onStart(Actor actor) {}
 
 	/**
 	 * This method specifies what happens when an Actor steps on a force field generator.
 	 * 
 	 * @param 	actor
 	 * 			This is the Actor stepping on the generator.
 	 */
 	@Override
 	public void onStep(Actor actor) {}
 
 	/**
 	 * This method specifies what happens when an Actor lands on a force field generator.
 	 * 
 	 * @param 	actor
 	 * 			This is the Actor landing on the generator.
 	 */
 	@Override
 	public void onLand(Actor actor) {}
 
 	/**
 	 * This method specifies what happens when an Actor leaves a force field generator.
 	 * 
 	 * @param 	actor
 	 * 			This is the Actor leaving the generator.
 	 */
 	@Override
 	public void onLeave(Actor actor) {}
 
 	/**
 	 * Checks whether the force field generator is visible on the grid.
 	 * 
 	 * @return 	True in this case.
 	 */
 	@Override
 	public boolean isVisible() {
 		return true;
 	}
 
 	/**
 	 * This method checks whether this force field generator can be on a square with the given items.
 	 * 
 	 * @param 	items
 	 * 			The items that are located on the square.
 	 * 
 	 * @return 	True in this case.
 	 */
 	@Override
 	public boolean canBeOnSquareWith(Item... items) {
 		return true;
 	}
 
 	/**
 	 * Checks whether the force field generator can be stepped on or not.
 	 * 
	 * @return 	True when there is no generated force field, otherwise false.
	 * 			| return getForceField().getNbSquares() == 0
 	 */
 	@Override
 	public boolean canBeSteppedOn() {
		return getForceField().getNbSquares() == 0;
 	}
 	
 	public void use()
 	{
 		super.use();
 		//TODO: shizzle
 		ForceField forcefield = new ForceField();
 		//forcefield.addSquares(this.getLocation(), destination, direction);
 		setForceField(forcefield);
 		//set force field on force field generator of destination square
 	}
 
 }
